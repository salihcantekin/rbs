#!/bin/sh
# Regenerates src/sys/va_api.rs from the libva headers (MIT licence). Needs
# bindgen-cli 0.73 and libclang. Run from the repository root. Only types and
# constants are generated; the entry points are declared in src/sys/mod.rs and
# loaded at run time. va_version.h is written here (libva generates it at build
# time) with the version of the tag.
set -eu
TAG=2.20.0
OUT=${OUT:-crates/rbs-codec-vaapi/src/sys/va_api.rs}
TMP=$(mktemp -d)
BASE="https://raw.githubusercontent.com/intel/libva/$TAG/va"
mkdir -p "$TMP/va"
for h in va.h va_dec_av1.h va_dec_hevc.h va_dec_jpeg.h va_dec_vp8.h va_dec_vp9.h \
  va_enc_av1.h va_enc_h264.h va_enc_hevc.h va_enc_jpeg.h va_enc_mpeg2.h va_enc_vp8.h \
  va_enc_vp9.h va_fei.h va_fei_h264.h va_fei_hevc.h va_prot.h va_vpp.h; do
  curl -sSfL -o "$TMP/va/$h" "$BASE/$h"
done
cat > "$TMP/va/va_version.h" <<'H'
#define VA_MAJOR_VERSION 1
#define VA_MINOR_VERSION 20
#define VA_MICRO_VERSION 0
#define VA_VERSION_S "1.20.0"
#define VA_CHECK_VERSION(major,minor,micro) \
  (VA_MAJOR_VERSION > (major) || \
   (VA_MAJOR_VERSION == (major) && VA_MINOR_VERSION > (minor)) || \
   (VA_MAJOR_VERSION == (major) && VA_MINOR_VERSION == (minor) && VA_MICRO_VERSION >= (micro)))
H
cat > "$TMP/wrapper.h" <<'H'
#include <va/va.h>
#include <va/va_enc_h264.h>
#include <va/va_enc_hevc.h>
H
# The types the adapter uses; bindgen adds what they depend on.
TYPES='VAStatus|VADisplay|VAProfile|VAEntrypoint|VAConfigAttribType|VAConfigAttrib|VAConfigID|VAContextID|VASurfaceID|VABufferID|VAImageID|VABufferType|VASurfaceStatus|VASurfaceAttrib|VASurfaceAttribType|VAGenericValueType|VAImage|VAImageFormat|VACodedBufferSegment|VAEncPackedHeaderType|VAEncPackedHeaderParameterBuffer|VAEncMiscParameterType|VAEncMiscParameterBuffer|VAEncMiscParameterRateControl|VAEncMiscParameterHRD|VAEncMiscParameterFrameRate|VAEncSequenceParameterBufferH264|VAEncPictureParameterBufferH264|VAEncSliceParameterBufferH264|VAEncSequenceParameterBufferHEVC|VAEncPictureParameterBufferHEVC|VAEncSliceParameterBufferHEVC|VAConfigAttribValEncHEVCFeatures|VAConfigAttribValEncHEVCBlockSizes|VAEncSliceStructure.*|VAMessageCallback'
bindgen "$TMP/wrapper.h" \
  --allowlist-type "$TYPES" --allowlist-var 'VA_.*' --blocklist-function '.*' \
  --no-doc-comments --use-core --default-enum-style consts --no-prepend-enum-name \
  --rust-target 1.87 --with-derive-default --no-debug '.*' \
  --raw-line "// Generated by bindgen 0.73.2 from libva $TAG (va/va.h, va_enc_h264.h, va_enc_hevc.h," \
  --raw-line '// MIT licence, "Copyright (c) 2007-2009 Intel Corporation"). Do not edit;' \
  --raw-line '// regenerate with crates/rbs-codec-vaapi/tools/bindgen.sh.' \
  -o "$OUT" -- -I"$TMP"
rm -rf "$TMP"
