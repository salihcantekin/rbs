//! Context menus built from the command registry (ADR-0050 decision 4; spec
//! `ui-design-system.md`, "Context menus").
//!
//! An element with a menu has a `CommandMenu` (`ui/context_menu.slint`) with its
//! context's name and a target, the parameters that name what was right-clicked
//! (`source=12&item=40`). Opening it asks [`items`] for the menu of the moment, from
//! [`rbs_ui::command::CONTEXT_LAYOUT`] and the shell's state; a picked item runs its
//! registry id like the menu bar does.
//!
//! Slint needs a menu's items written out, so `CommandMenu` declares
//! [`rbs_ui::command::MAX_CONTEXT_ITEMS`] slots, each drawn as a command, a separator or a submenu by
//! its item's kind. The slots are generated by `slint_text` (tests only) between
//! marker lines in `ui/context_menu.slint`; a test fails when that copy is out of date
//! (run it with `RBS_UPDATE_MENU_BAR=1` to rewrite it).

#[cfg(test)]
use rbs_ui::command::MAX_CONTEXT_ITEMS;
use rbs_ui::command::{CommandId, CommandState, Context, MenuItem, context_menu};

use crate::menu_bar::item_icon;

/// What a slot draws (`ContextItem.kind`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    Command = 1,
    Separator = 2,
    Choices = 3,
}

/// One item as the toolkit gets it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Item {
    pub kind: Kind,
    pub title: String,
    /// Icon name from the set; empty while a checkmark takes its place.
    pub icon: &'static str,
    /// The registry id a click runs; empty for separators and submenus.
    pub id: String,
    pub enabled: bool,
    pub checkable: bool,
    pub checked: bool,
    /// `(title, id to run, current)` of a submenu.
    pub choices: Vec<(String, String, bool)>,
}

/// The parameters in `target` (`key=value&...`, percent-encoded as in command ids);
/// `None` when it does not parse.
pub fn target(text: &str) -> Option<Vec<(String, String)>> {
    if text.is_empty() {
        return Some(Vec::new());
    }
    let id = CommandId::parse(&format!("context.target?{text}")).ok()?;
    Some(id.params().to_vec())
}

/// The items of `context`'s menu for `target`.
pub fn items(context: Context, target: &[(String, String)], state: &dyn CommandState) -> Vec<Item> {
    context_menu(context, target, state)
        .into_iter()
        .map(|i| match i {
            MenuItem::Command {
                id,
                title,
                disabled,
                checked,
                icon,
                ..
            } => Item {
                kind: Kind::Command,
                title,
                icon: item_icon(icon, checked),
                id: id.to_string(),
                enabled: disabled.is_none(),
                checkable: checked.is_some(),
                checked: checked.unwrap_or(false),
                choices: Vec::new(),
            },
            MenuItem::Choices {
                title,
                icon,
                choices,
            } => Item {
                kind: Kind::Choices,
                title,
                icon: item_icon(icon, None),
                id: String::new(),
                enabled: !choices.is_empty(),
                checkable: false,
                checked: false,
                choices: choices
                    .into_iter()
                    .map(|(t, id, current)| (t, id.to_string(), current))
                    .collect(),
            },
            MenuItem::Separator => Item {
                kind: Kind::Separator,
                title: String::new(),
                icon: "",
                id: String::new(),
                enabled: true,
                checkable: false,
                checked: false,
                choices: Vec::new(),
            },
        })
        .collect()
}

#[cfg(test)]
/// The generated slots, each line indented by `indent`.
pub fn slint_text(indent: &str) -> String {
    let mut out = String::new();
    // `for` over zero or one, not `if`: Slint 1.18 lists only the first of several
    // conditional items in a context menu.
    for i in 0..MAX_CONTEXT_ITEMS {
        let it = format!("ContextMenus.items[{i}]");
        out.push_str(&format!(
            "{indent}for _ in {it}.kind == 1 ? 1 : 0: MenuItem {{ title: {it}.title; icon: {it}.icon; enabled: {it}.enabled; checkable: {it}.checkable; checked: {it}.checked; activated => {{ ContextMenus.run({it}.id); }} }}\n"
        ));
        out.push_str(&format!(
            "{indent}for _ in {it}.kind == 2 ? 1 : 0: MenuSeparator {{ }}\n"
        ));
        out.push_str(&format!(
            "{indent}for _ in {it}.kind == 3 ? 1 : 0: Menu {{ title: {it}.title; icon: {it}.icon; enabled: {it}.enabled; for c in {it}.choices: MenuItem {{ title: c.title; checkable: true; checked: c.checked; activated => {{ ContextMenus.run(c.id); }} }} }}\n"
        ));
    }
    out
}

#[cfg(test)]
pub const BEGIN: &str = "// BEGIN generated context menu slots (context_menu.rs; do not edit)";
#[cfg(test)]
pub const END: &str = "// END generated context menu slots";

#[cfg(test)]
/// `text` with the generated slots replaced by the current ones, or `None` without
/// the marker pair.
pub fn refreshed(text: &str) -> Option<String> {
    let begin = text.find(BEGIN)?;
    let line_start = text[..begin].rfind('\n').map_or(0, |i| i + 1);
    let indent = &text[line_start..begin];
    let after = begin + BEGIN.len();
    let end = after + text[after..].find(END)?;
    let end_line = text[..end].rfind('\n').map_or(0, |i| i + 1);
    let mut out = String::with_capacity(text.len());
    out.push_str(&text[..after]);
    out.push('\n');
    out.push_str(&slint_text(indent));
    out.push_str(&text[end_line..]);
    Some(out)
}

#[cfg(test)]
#[allow(clippy::expect_used, clippy::unwrap_used)] // Tests fail by panicking.
mod tests {
    use super::*;

    const SLINT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/ui/context_menu.slint");

    #[test]
    fn context_menu_slint_has_the_current_slots() {
        let text = std::fs::read_to_string(SLINT).expect("ui/context_menu.slint is readable");
        let text = text.replace("\r\n", "\n");
        let fresh = refreshed(&text).expect("ui/context_menu.slint has the slot markers");
        if fresh != text && std::env::var_os("RBS_UPDATE_MENU_BAR").is_some() {
            std::fs::write(SLINT, &fresh).expect("ui/context_menu.slint is writable");
            return;
        }
        assert!(
            fresh == text,
            "the slots in ui/context_menu.slint are out of date: run \
             `RBS_UPDATE_MENU_BAR=1 cargo test -p rbs-app --bin rbs context_menu`"
        );
    }

    #[test]
    fn targets_parse_as_id_parameters() {
        assert_eq!(target(""), Some(Vec::new()));
        assert_eq!(
            target("source=12&item=40").unwrap(),
            vec![
                ("item".to_owned(), "40".to_owned()),
                ("source".to_owned(), "12".to_owned())
            ]
        );
        assert_eq!(target("name=A%20b").unwrap()[0].1, "A b");
        assert_eq!(target("bad"), None);
        assert_eq!(target("x=a b"), None);
    }

    struct All;

    impl CommandState for All {
        fn enabled(&self, _: &CommandId) -> Result<(), String> {
            Ok(())
        }
        fn checked(&self, id: &CommandId) -> bool {
            id.base() == "item.visible.toggle"
        }
        fn choices(&self, _: &CommandId) -> Vec<(String, String, bool)> {
            vec![("Screen".into(), "screen".into(), false)]
        }
    }

    #[test]
    fn every_context_fits_its_slots() {
        let target = target("scene=1&source=2&item=3").unwrap();
        for c in Context::ALL {
            let items = items(c, &target, &All);
            assert!(!items.is_empty(), "{c:?}");
            assert!(items.len() <= MAX_CONTEXT_ITEMS, "{c:?}");
        }
    }

    #[test]
    fn items_carry_ids_states_and_submenus() {
        let target = target("source=2&item=3").unwrap();
        let source = items(Context::Source, &target, &All);
        let visible = source
            .iter()
            .find(|i| i.id == "item.visible.toggle?item=3")
            .unwrap();
        assert!(visible.checkable && visible.checked);
        assert_eq!(visible.icon, "", "a checkmark takes the icon's place");
        assert_eq!(source[0].id, "item.flip?axis=horizontal&item=3");
        assert!(
            source
                .iter()
                .any(|i| i.kind == Kind::Choices && i.choices.len() == 1)
        );
        assert!(
            source
                .iter()
                .all(|i| i.kind == Kind::Separator || i.checked || !i.icon.is_empty())
        );
        assert!(source.iter().any(|i| i.id == "source.delete?source=2"));
        let sources = items(Context::Sources, &[], &All);
        assert_eq!(sources[0].kind, Kind::Choices);
        assert_eq!(sources[0].choices[0].1, "source.add?kind=screen");
    }
}
