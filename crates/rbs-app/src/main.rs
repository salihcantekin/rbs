/// Connects one window's `Sections` global to the workspace's closed sections.
fn install_sections(g: &Sections<'_>, ctx: &Ctx) {
    // Pure: Slint asks again when `rev` changes. While the app is busy (never at
    // render time) the section shows open.
    let c = ctx.clone();
    g.on_closed(move |id, _rev| {
        let (key, listed_is_closed) = section_key(id.as_str());
        c.app
            .try_borrow()
            // Busy (never at render time): the section's default.
            .map_or(!listed_is_closed, |app| {
                app.session.workspace().section_closed(&key) == listed_is_closed
            })
    });
    let c = ctx.clone();
    g.on_group_state(move |prefix, _rev| {
        c.app.try_borrow().map_or(0, |app| {
            let ws = app.session.workspace();
            let mut cards = SETTINGS_SECTIONS
                .iter()
                .filter(|id| id.starts_with(prefix.as_str()));
            match cards.next() {
                None => 0,
                Some(_)
                    if SETTINGS_SECTIONS
                        .iter()
                        .filter(|id| id.starts_with(prefix.as_str()))
                        .all(|id| ws.section_closed(id)) =>
                {
                    2
                }
                Some(_) => 1,
            }
        })
    });
    let c = ctx.clone();
    g.on_set_group(move |prefix, closed| {
        c.update(move |app: &mut App| {
            let mut changed = false;
            for id in SETTINGS_SECTIONS
                .iter()
                .filter(|id| id.starts_with(prefix.as_str()))
            {
                changed |= app.session.set_section_closed(id, closed).is_ok();
            }
            if changed {
                app.changed();
            }
        });
    });
    let c = ctx.clone();
    g.on_set_closed(move |id, closed| {
        let (key, listed_is_closed) = section_key(id.as_str());
        c.update(move |app: &mut App| {
            if app
                .session
                .set_section_closed(&key, closed == listed_is_closed)
                .is_ok()
            {
                app.changed();
            }
        });
    });
    let c = ctx.clone();
    g.on_set_mixer_scene_share(move |share| {
        c.update(move |app: &mut App| {
            app.session.set_mixer_scene_share(share);
            app.changed();
        });
    });
}

/// Opens the Source settings window for a source (centred on the main window; one at a
/// time: another source's replaces the content of the open one).
fn open_source_settings(ctx: &Ctx, app: &mut App, id: i32) {
    app.studio.request_source_settings(id);
    if let Some(w) = &app.source_settings {
        // Already open: bring it forward; keep the place the user left it.
        window_place::raise(w.window());
        return;
    }
    let Ok(w) = SourceSettingsWindow::new() else {
        app.show_error(UiError::Other(
            "The source settings window cannot be opened.".into(),
        ));
        return;
    };
    rbs_app::window_events::install(&w);
    look::apply(
        &w.global::<Theme>(),
        &w.global::<Tokens>(),
        ctx.look.borrow().as_ref(),
    );
    install_studio(&w.global::<Studio>(), ctx);
    app.studio.attach_models(&w.global::<Studio>());
    let c = ctx.clone();
    entry::on_close_requested(w.window(), move || {
        c.update(|app| {
            app.source_settings = None;
            app.studio.source_settings_closed();
        });
        slint::CloseRequestResponse::HideWindow
    });
    let (weak, c) = (w.as_weak(), ctx.clone());
    w.on_dismiss(move || {
        entry::guard(|| {
            if let Some(w) = weak.upgrade() {
                let _ = w.hide();
            }
            c.update(|app| {
                app.source_settings = None;
                app.studio.source_settings_closed();
            });
        });
    });
    let t = w.global::<Tokens>();
    let size = slint::LogicalSize::new(t.get_size_floating_w(), t.get_size_floating_h());
    let _ = window_place::show_centred(&w, &app.main, size, app.hidden);
    let _ = exclude_window_from_capture(w.window(), app.bg.exclude_own_window);
    app.capture_applied.1 = usize::MAX;
    app.capture_retry = None;
    app.source_settings = Some(w);
}

