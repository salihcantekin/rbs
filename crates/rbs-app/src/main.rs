/// The system file dialog for import and export (ADR-0051).
mod file_dialog {
    use std::path::PathBuf;

    /// A file to import; `Ok(None)` when cancelled.
    #[cfg(any(target_os = "macos", windows))]
    pub async fn open(title: &str) -> Result<Option<PathBuf>, String> {
        Ok(rfd::AsyncFileDialog::new()
            .set_title(title)
            .add_filter("RBS settings", &["toml"])
            .pick_file()
            .await
            .map(|f| f.path().to_owned()))
    }

    /// A PNG picture; `Ok(None)` when cancelled.
    #[cfg(any(target_os = "macos", windows))]
    pub async fn open_png(title: &str) -> Result<Option<PathBuf>, String> {
        Ok(rfd::AsyncFileDialog::new()
            .set_title(title)
            .add_filter("PNG image", &["png"])
            .pick_file()
            .await
            .map(|f| f.path().to_owned()))
    }

    /// A media file for the Media source; `Ok(None)` when cancelled.
    /// The demo decoder accepts any regular file (bytes ignored).
    #[cfg(any(target_os = "macos", windows))]
    pub async fn open_media(title: &str) -> Result<Option<PathBuf>, String> {
        Ok(rfd::AsyncFileDialog::new()
            .set_title(title)
            .add_filter(
                "Media",
                &[
                    "mp4", "mkv", "webm", "mov", "m4v", "mp3", "wav", "flac", "aac",
                ],
            )
            .add_filter("All files", &["*"])
            .pick_file()
            .await
            .map(|f| f.path().to_owned()))
    }

    /// Where to export; `Ok(None)` when cancelled.
    #[cfg(any(target_os = "macos", windows))]
    pub async fn save(title: &str, file_name: &str) -> Result<Option<PathBuf>, String> {
        Ok(rfd::AsyncFileDialog::new()
            .set_title(title)
            .add_filter("RBS settings", &["toml"])
            .set_file_name(file_name)
            .save_file()
            .await
            .map(|f| f.path().to_owned()))
    }

    #[cfg(not(any(target_os = "macos", windows)))]
    const NONE: &str = "Import and export need a file dialog, which RBS does not have on this system yet. Copy the files in the profiles or scenes folder of the settings folder instead.";

    #[cfg(not(any(target_os = "macos", windows)))]
    pub async fn open(_title: &str) -> Result<Option<PathBuf>, String> {
        Err(NONE.into())
    }

    #[cfg(not(any(target_os = "macos", windows)))]
    pub async fn open_png(_title: &str) -> Result<Option<PathBuf>, String> {
        Err(NONE.into())
    }

    #[cfg(not(any(target_os = "macos", windows)))]
    pub async fn open_media(_title: &str) -> Result<Option<PathBuf>, String> {
        Err(NONE.into())
    }

    #[cfg(not(any(target_os = "macos", windows)))]
    pub async fn save(_title: &str, _file_name: &str) -> Result<Option<PathBuf>, String> {
        Err(NONE.into())
    }
}

