/// How long a toast stays before it dismisses itself.
const TOAST_TIME: Duration = Duration::from_secs(8);

/// Layout changes are written to disk after this quiet time, not on every change (U5).
const SAVE_DELAY: Duration = Duration::from_millis(400);

/// An error shown in the error bar.
enum UiError {
    Locked,
    Other(String),
}

/// Row models of one window's dock area. They live as long as the window, so
/// unchanged rows keep their view instances (and keyboard focus).
struct DockModels {
    stacks: Rc<VecModel<StackData>>,
    handles: Rc<VecModel<HandleData>>,
}

impl DockModels {
    fn new() -> Self {
        DockModels {
            stacks: Rc::new(VecModel::default()),
            handles: Rc::new(VecModel::default()),
        }
    }

    fn update(&self, stacks: Vec<StackData>, handles: Vec<HandleData>) {
        let stacks = stacks
            .into_iter()
            .enumerate()
            .map(|(i, mut s)| {
                // Keep the old tab model when the tabs are the same, so the tab
                // views are not rebuilt.
                if let Some(old) = self.stacks.row_data(i)
                    && same_tabs(&old.tabs, &s.tabs)
                {
                    s.tabs = old.tabs;
                }
                s
            })
            .collect();
        set_rows(&self.stacks, stacks);
        set_rows(&self.handles, handles);
    }
}

fn same_tabs(a: &ModelRc<TabData>, b: &ModelRc<TabData>) -> bool {
    a.row_count() == b.row_count() && a.iter().zip(b.iter()).all(|(x, y)| x == y)
}

/// Replace rows that changed; rebuild only when the number of rows changes.
fn set_rows<T: Clone + PartialEq + 'static>(model: &VecModel<T>, rows: Vec<T>) {
    if model.row_count() != rows.len() {
        model.set_vec(rows);
        return;
    }
    for (i, row) in rows.into_iter().enumerate() {
        if model.row_data(i).as_ref() != Some(&row) {
            model.set_row_data(i, row);
        }
    }
}

/// One floating OS window. `panels` are the panels it showed at the last sync,
/// which identify its workspace window across index changes (dock, undo,
/// switch); `index` is that workspace window's index at the last sync.
struct FloatSlot {
    window: FloatWindow,
    panels: Vec<PanelId>,
    index: Option<usize>,
    models: DockModels,
}

struct App {
    session: LayoutSession,
    store: WorkspaceStore,
    config: PathBuf,
    workspaces: Vec<(String, bool)>,
    main: MainWindow,
    main_models: DockModels,
    panels_model: Rc<VecModel<PanelEntry>>,
    workspaces_model: Rc<VecModel<WorkspaceEntry>>,
    floats: Vec<FloatSlot>,
    areas: Vec<(usize, Rect)>,
    drag_group: Option<u64>,
    next_group: u64,
    toast: Option<Toast>,
    toast_serial: u64,
    error: Option<UiError>,
    save_due: bool,
    exiting: bool,
    demo_since: Option<Instant>,
    studio: studio_ui::StudioUi,
    /// The Settings window while it is open (U17).
    settings: Option<SettingsWindow>,
}

impl App {
    fn default_area(&self, window: usize) -> Rect {
        let t = self.main.global::<Tokens>();
        if window == 0 {
            Rect::sized(t.get_size_window_w(), t.get_size_window_h())
        } else {
            Rect::sized(t.get_size_floating_w(), t.get_size_floating_h())
        }
    }

    fn area(&self, window: usize) -> Rect {
        self.areas
            .iter()
            .find(|(w, _)| *w == window)
            .map_or_else(|| self.default_area(window), |(_, r)| *r)
    }

    fn set_area(&mut self, window: usize, r: Rect) {
        match self.areas.iter_mut().find(|(w, _)| *w == window) {
            Some(entry) => entry.1 = r,
            None => self.areas.push((window, r)),
        }
    }

    fn refresh_list(&mut self) {
        match self.store.list() {
            Ok(l) => {
                self.workspaces = l
                    .workspaces
                    .into_iter()
                    .map(|w| (w.name, w.built_in))
                    .collect();
                if let Some((path, e)) = l.problems.first() {
                    self.error = Some(UiError::Other(format!("{}: {e}", path.display())));
                }
            }
            Err(e) => self.error = Some(UiError::Other(e.to_string())),
        }
    }

    /// Save the current workspace now and remember it for the next start.
    fn persist_now(&mut self) {
        self.save_due = false;
        let ws = self.session.workspace();
        let result = self.store.save(ws).map(|_| ()).and_then(|()| {
            config::set_last_workspace(&self.config, &ws.name).map_err(StoreError::Io)
        });
        if let Err(e) = result {
            self.error = Some(UiError::Other(e.to_string()));
        }
    }

    fn command(&mut self, c: LayoutCommand, origin: Origin) {
        // Leaving a workspace: write its pending changes first, because the
        // debounced save only ever writes the current workspace.
        if matches!(c, LayoutCommand::Switch(_)) {
            self.flush();
        }
        match self.session.apply(c, origin) {
            Ok(toast) => {
                // A toast's undo always means the latest change, so any later
                // change replaces or removes it.
                self.set_toast(toast);
                self.changed();
            }
            Err(CommandError::Locked) => self.error = Some(UiError::Locked),
            Err(e) => self.error = Some(UiError::Other(e.to_string())),
        }
    }

    fn set_toast(&mut self, toast: Option<Toast>) {
        if toast.is_some() {
            self.toast_serial += 1;
        }
        self.toast = toast;
    }

    /// After any layout change: save soon. Window sizes are re-keyed in
    /// `sync_floats`, which knows which OS window shows which workspace window.
    fn changed(&mut self) {
        self.save_due = true;
    }

    /// Write pending changes now. Called before anything that may leave the
    /// current workspace or reload it from disk (switch, undo, redo).
    fn flush(&mut self) {
        if self.save_due {
            self.persist_now();
        }
    }

    fn undo(&mut self) {
        self.flush();
        if self.session.undo() {
            self.toast = None;
            self.changed();
        }
    }

    fn redo(&mut self) {
        self.flush();
        if self.session.redo() {
            self.toast = None;
            self.changed();
        }
    }

    fn drag(&mut self, window: usize, handle: usize, position: f32) {
        let area = self.area(window);
        let Some(h) = self
            .session
            .workspace()
            .windows
            .get(window)
            .and_then(|w| w.layout())
            .and_then(|l| l.flatten(area).handles.get(handle).cloned())
        else {
            return;
        };
        let current = match h.axis {
            Axis::Horizontal => h.rect.x,
            Axis::Vertical => h.rect.y,
        };
        let delta = position - current;
        if delta.abs() < 0.5 {
            return;
        }
        let group = match self.drag_group {
            Some(g) => g,
            None => {
                self.next_group += 1;
                self.drag_group = Some(self.next_group);
                self.next_group
            }
        };
        let c = LayoutCommand::Resize {
            window,
            area,
            handle,
            delta,
            group: Some(group),
        };
        self.command(c, Origin::Pointer);
    }

    fn end_drag(&mut self) {
        if self.drag_group.take().is_some() {
            self.session.end_group();
        }
    }
}

type Op = Box<dyn FnOnce(&mut App)>;

#[derive(Clone)]
struct Ctx {
    app: Rc<RefCell<App>>,
    /// Changes asked for while the state was borrowed; applied before the next sync.
    queue: Rc<RefCell<Vec<Op>>>,
    pending: Rc<Cell<bool>>,
    /// Dismisses a toast after [`TOAST_TIME`]; runs only while a toast is shown.
    toast_timer: Rc<slint::Timer>,
    toast_shown: Rc<Cell<u64>>,
    /// Writes the layout [`SAVE_DELAY`] after the last change.
    save_timer: Rc<slint::Timer>,
    /// Refreshes the meters; runs only while the Mixer shows audio sources (U5, U16).
    meter_timer: Rc<slint::Timer>,
    /// Dismisses the "deleted" toast after [`TOAST_TIME`].
    deleted_timer: Rc<slint::Timer>,
    deleted_shown: Rc<Cell<u64>>,
    /// Ticks the live duration once a second while live or recording.
    live_timer: Rc<slint::Timer>,
}

/// Sections of the Settings window (`SettingsWindow.section`).
const SECTION_RECORDING: i32 = 1;
const SECTION_STREAM: i32 = 2;

thread_local! {
    /// The shell's context, for updates the studio's control thread hands to the UI
    /// thread (`slint::invoke_from_event_loop` takes only `Send` closures).
    static CTX: RefCell<Option<Ctx>> = const { RefCell::new(None) };
}

/// Hands an update from the studio's control thread to the UI thread.
fn deliver(u: studio_host::Update) {
    let _ = slint::invoke_from_event_loop(move || {
        let ctx = CTX.with(|c| c.borrow().clone());
        if let Some(ctx) = ctx {
            ctx.studio_update(u);
        }
    });
}

impl Ctx {
    /// Change the state, then update the views once on the next event loop turn.
    /// Views are never updated from inside a callback, so creating or hiding
    /// windows cannot re-enter borrowed state.
    fn update(&self, f: impl FnOnce(&mut App) + 'static) {
        match self.app.try_borrow_mut() {
            Ok(mut app) => f(&mut app),
            Err(_) => self.queue.borrow_mut().push(Box::new(f)),
        }
        if !self.pending.replace(true) {
            let ctx = self.clone();
            slint::Timer::single_shot(Duration::ZERO, move || {
                ctx.pending.set(false);
                ctx.sync();
            });
        }
    }

    /// Update only the live duration (the 1 Hz tick while live or recording).
    fn live_tick(&self) {
        let Ok(mut app) = self.app.try_borrow_mut() else {
            return;
        };
        // Since going live while live, else since the recording started.
        let elapsed = match (
            app.demo_since,
            app.studio.streaming_for(),
            app.studio.recording_for(),
        ) {
            (Some(since), _, _) => since.elapsed(),
            (None, Some((d, _, _)), _) | (None, None, Some((d, _))) => d,
            (None, None, None) => return,
        };
        let mut live = app.session.live().clone();
        live.elapsed_secs = elapsed.as_secs();
        let text: slint::SharedString = live.duration_text().into();
        app.session.set_live(live);
        app.main.global::<Shell>().set_live_duration(text.clone());
        for f in &app.floats {
            f.window.global::<Shell>().set_live_duration(text.clone());
        }
    }

    /// Applies an update from the studio.
    fn studio_update(&self, u: studio_host::Update) {
        let ctx = self.clone();
        self.update(move |app| {
            let applied = app.studio.apply(u);
            if let Some(e) = applied.error {
                app.error = Some(UiError::Other(e));
            }
            if let Some(endpoint) = applied.preview {
                ctx.connect_preview(endpoint);
            }
        });
    }

    #[cfg(any(target_os = "macos", windows))]
    fn connect_preview(&self, endpoint: rbs_gpu::share::PreviewEndpoint) {
        preview::connect(endpoint, |ok| {
            let ctx = CTX.with(|c| c.borrow().clone());
            if let Some(ctx) = ctx {
                ctx.update(move |app| {
                    app.studio.preview_ready = ok;
                    app.studio.preview_failed = !ok;
                });
            }
        });
    }

    #[cfg(not(any(target_os = "macos", windows)))]
    fn connect_preview(&self, _endpoint: rbs_gpu::share::PreviewEndpoint) {}

    /// Shows the Settings window at `section`, made on first use and kept until it is
    /// closed.
    fn open_settings(&self, section: i32) {
        let ctx = self.clone();
        self.update(move |app| {
            app.studio.settings_opened();
            if let Some(w) = &app.settings {
                w.set_section(section);
                let _ = w.show();
                return;
            }
            let Ok(w) = SettingsWindow::new() else {
                app.error = Some(UiError::Other(
                    "The settings window cannot be opened.".into(),
                ));
                return;
            };
            apply_theme(&w.global::<Theme>());
            install_studio(&w.global::<Studio>(), &ctx);
            // `install_studio` cannot borrow the app here (this runs inside an update):
            // the shared models (the access token list) are attached directly.
            app.studio.attach_models(&w.global::<Studio>());
            let c = ctx.clone();
            w.window().on_close_requested(move || {
                c.update(|app| {
                    app.settings = None;
                    app.studio.settings_closed();
                });
                slint::CloseRequestResponse::HideWindow
            });
            // Escape: hidden and dropped as by the close button. The strong handle
            // keeps the window alive until the callback returns.
            let weak = w.as_weak();
            let c = ctx.clone();
            w.on_dismiss(move || {
                let Some(w) = weak.upgrade() else {
                    return;
                };
                let _ = w.hide();
                c.update(|app| {
                    app.settings = None;
                    app.studio.settings_closed();
                });
            });
            w.set_section(section);
            let _ = w.show();
            app.settings = Some(w);
        });
    }

    /// One meter refresh (the timer runs only while the Mixer shows meters).
    fn meter_tick(&self) {
        if let Ok(mut app) = self.app.try_borrow_mut() {
            app.studio.tick_meters();
        }
    }

    /// Where the studio's panels are and what they show; starts and stops the meter
    /// timer and places the preview layer.
    /// The live status from the studio, and the 1 Hz duration tick while live or
    /// recording.
    fn sync_live(&self, app: &mut App) {
        // The live indicator follows the stream and the recording.
        if app.demo_since.is_none() {
            let live = match (app.studio.streaming_for(), app.studio.recording_for()) {
                (Some((d, host, connected)), rec) => LiveStatus {
                    live: true,
                    recording: rec.is_some(),
                    elapsed_secs: d.as_secs(),
                    outputs: std::iter::once(if connected {
                        host
                    } else {
                        format!("{host} not connected")
                    })
                    .chain(rec.map(|(_, file)| file))
                    .collect(),
                },
                (None, Some((d, file))) => LiveStatus {
                    live: false,
                    recording: true,
                    elapsed_secs: d.as_secs(),
                    outputs: vec![file],
                },
                (None, None) => LiveStatus::default(),
            };
            if *app.session.live() != live {
                app.session.set_live(live);
            }
        }
        // One tick a second while live or recording, none otherwise (ADR-0013).
        if app.session.live().is_active() {
            if !self.live_timer.running() {
                let ctx = self.clone();
                self.live_timer.start(
                    slint::TimerMode::Repeated,
                    Duration::from_secs(1),
                    move || ctx.live_tick(),
                );
            }
        } else {
            self.live_timer.stop();
        }
    }

    fn sync_studio(&self, app: &mut App) {
        let t = app.main.global::<Tokens>();
        let bar = t.get_size_control_md() + 2.0 * t.get_space_1();
        let border = t.get_size_border();
        let frame = t.get_size_control_md() + 2.0 * t.get_space_2();
        let in_main = |id: &str| {
            studio_ui::active_content(&app.main_models.stacks, id, bar, border)
                .map(|[x, y, w, h]| [x, y + frame, w, h])
        };
        let float_has = |id: &str| {
            app.floats
                .iter()
                .any(|f| studio_ui::active_content(&f.models.stacks, id, bar, border).is_some())
        };
        // Without studio mode Program and Preview both show the scene on air; the picture
        // goes to Program when it is shown, else to Preview.
        let panel = if in_main("rbs.program").is_some() || float_has("rbs.program") {
            "rbs.program"
        } else {
            "rbs.preview"
        };
        let picture_main = in_main(panel);
        if let Some([_, _, w, h]) = picture_main {
            app.studio.set_picture_size(w, h);
        }
        let mixer_shown = in_main("rbs.mixer").is_some() || float_has("rbs.mixer");
        use studio_ui::preview_state as ps;
        let s = &app.studio;
        let state = match s.state {
            0 => ps::STARTING,
            2 => ps::STOPPED,
            _ if !s.preview_offered => ps::NO_PLATFORM,
            _ if s.preview_failed => ps::NO_SESSION,
            _ if picture_main.is_none() && float_has(panel) => ps::OTHER_WINDOW,
            _ if s.preview_ready => ps::SHOWN,
            _ => ps::STARTING,
        };
        s.push(&app.main.global::<Studio>(), state, panel);
        for f in &app.floats {
            s.push(&f.window.global::<Studio>(), state, panel);
        }
        if let Some(w) = &app.settings {
            s.push(&w.global::<Studio>(), state, panel);
        }

        if mixer_shown && s.has_meters() {
            if !self.meter_timer.running() {
                let ctx = self.clone();
                self.meter_timer.start(
                    slint::TimerMode::Repeated,
                    studio_ui::METER_PERIOD,
                    move || ctx.meter_tick(),
                );
            }
        } else {
            self.meter_timer.stop();
        }

        if !s.deleted.is_empty() {
            if self.deleted_shown.get() != s.deleted_serial || !self.deleted_timer.running() {
                self.deleted_shown.set(s.deleted_serial);
                let ctx = self.clone();
                self.deleted_timer
                    .start(slint::TimerMode::SingleShot, TOAST_TIME, move || {
                        ctx.update(|app| app.studio.deleted.clear());
                    });
            }
        } else {
            self.deleted_timer.stop();
        }

        #[cfg(any(target_os = "macos", windows))]
        {
            preview::set_area(picture_main);
            preview::place(&app.main);
            preview::set_marks(&app.main, app.studio.marks());
        }
    }

    fn sync(&self) {
        let Ok(mut app) = self.app.try_borrow_mut() else {
            return;
        };
        let queued: Vec<Op> = std::mem::take(&mut *self.queue.borrow_mut());
        for op in queued {
            op(&mut app);
        }
        if app.exiting {
            return;
        }
        self.sync_live(&mut app);

        // Main window.
        let (stacks, handles) = view::window_view(0, app.session.workspace().main(), app.area(0));
        app.main_models.update(stacks, handles);

        self.sync_floats(&mut app);

        // Shared state, pushed into every window's copy of the global.
        set_rows(
            &app.panels_model,
            view::panel_entries(app.session.workspace()),
        );
        let entries = view::workspace_entries(&app.workspaces, &app.session.workspace().name);
        set_rows(&app.workspaces_model, entries);
        let ws = app.session.workspace();
        let live = app.session.live();
        let (toast_kind, toast_subject) = match &app.toast {
            Some(Toast::ClosedWhileLive(id)) => (1, view::title(id)),
            Some(Toast::SwitchedAutomatically { previous }) => (2, previous.clone()),
            None => (0, String::new()),
        };
        let (error_kind, error_detail) = match &app.error {
            Some(UiError::Locked) => (1, String::new()),
            Some(UiError::Other(e)) => (2, e.clone()),
            None => (0, String::new()),
        };
        let panels = ModelRc::from(app.panels_model.clone());
        let workspaces = ModelRc::from(app.workspaces_model.clone());
        let push = |g: Shell<'_>| {
            g.set_live_state(view::live_code(live));
            g.set_live_duration(live.duration_text().into());
            g.set_live_outputs(live.outputs_text().into());
            g.set_panels(panels.clone());
            g.set_workspaces(workspaces.clone());
            g.set_workspace_name(ws.name.as_str().into());
            g.set_workspace_built_in(builtin::is_built_in(&ws.name));
            g.set_locked(ws.locked);
            g.set_can_undo(app.session.can_undo());
            g.set_can_redo(app.session.can_redo());
            g.set_toast_kind(toast_kind);
            g.set_toast_subject(toast_subject.as_str().into());
            g.set_error_kind(error_kind);
            g.set_error_detail(error_detail.as_str().into());
        };
        push(app.main.global::<Shell>());
        for f in &app.floats {
            push(f.window.global::<Shell>());
        }

        if app.toast.is_some() {
            if self.toast_shown.get() != app.toast_serial || !self.toast_timer.running() {
                self.toast_shown.set(app.toast_serial);
                let ctx = self.clone();
                self.toast_timer
                    .start(slint::TimerMode::SingleShot, TOAST_TIME, move || {
                        ctx.update(|app| app.toast = None);
                    });
            }
        } else {
            self.toast_timer.stop();
        }
        self.sync_studio(&mut app);
        if app.save_due {
            let ctx = self.clone();
            self.save_timer
                .start(slint::TimerMode::SingleShot, SAVE_DELAY, move || {
                    ctx.update(App::persist_now);
                });
        }
    }

    /// One OS window per floating workspace window. An OS window keeps showing
    /// the workspace window that shares a panel with it, so its position, size
    /// and focus survive docks, moves and undo; leftover OS windows are reused
    /// in order before a new one is created.
    fn sync_floats(&self, app: &mut App) {
        let ws = app.session.workspace();
        let wanted: Vec<(usize, Vec<PanelId>)> = ws
            .windows
            .iter()
            .enumerate()
            .filter(|(_, w)| matches!(w.content, WindowContent::Floating(_)))
            .filter_map(|(i, w)| {
                w.layout()
                    .map(|l| (i, l.panels().into_iter().cloned().collect()))
            })
            .collect();
        let mut old: Vec<Option<FloatSlot>> = std::mem::take(&mut app.floats)
            .into_iter()
            .map(Some)
            .collect();
        let mut chosen: Vec<Option<FloatSlot>> = wanted
            .iter()
            .map(|(_, panels)| {
                old.iter_mut()
                    .find(|s| {
                        s.as_ref()
                            .is_some_and(|s| s.panels.iter().any(|p| panels.contains(p)))
                    })
                    .and_then(Option::take)
            })
            .collect();
        let mut leftover = old.into_iter().flatten();
        for c in chosen.iter_mut().filter(|c| c.is_none()) {
            *c = leftover.next();
        }
        for s in leftover {
            let _ = s.window.hide();
        }

        // Sizes follow their OS window to its new workspace window index.
        let old_areas = std::mem::take(&mut app.areas);
        let area_of = |i: usize| old_areas.iter().find(|(w, _)| *w == i).map(|(_, r)| *r);
        app.areas.extend(area_of(0).map(|r| (0, r)));
        let mut slots = Vec::with_capacity(wanted.len());
        for ((w, panels), slot) in wanted.into_iter().zip(chosen) {
            let Some(slot) = slot.or_else(|| self.new_float()) else {
                continue;
            };
            if let Some(r) = slot.index.and_then(area_of) {
                app.areas.push((w, r));
            }
            let Some(layout) = app.session.workspace().windows[w].layout() else {
                continue;
            };
            let (stacks, handles) = view::window_view(w, layout, app.area(w));
            slot.models.update(stacks, handles);
            slot.window.set_window(w as i32);
            slot.window.set_panel_names(view::panel_names(layout));
            slots.push(FloatSlot {
                panels,
                index: Some(w),
                ..slot
            });
        }
        app.floats = slots;
    }

    fn new_float(&self) -> Option<FloatSlot> {
        let fw = FloatWindow::new().ok()?;
        install(&fw.global::<Shell>(), self);
        install_studio(&fw.global::<Studio>(), self);
        apply_theme(&fw.global::<Theme>());
        let models = DockModels::new();
        fw.set_stacks(ModelRc::from(models.stacks.clone()));
        fw.set_handles(ModelRc::from(models.handles.clone()));
        let ctx = self.clone();
        let weak = fw.as_weak();
        fw.window().on_close_requested(move || {
            if let Some(fw) = weak.upgrade() {
                let w = fw.get_window() as usize;
                ctx.update(move |app| {
                    if !app.exiting {
                        app.command(LayoutCommand::CloseWindow { window: w }, Origin::Command);
                    }
                });
            }
            slint::CloseRequestResponse::HideWindow
        });
        let _ = fw.show();
        Some(FloatSlot {
            window: fw,
            panels: Vec::new(),
            index: None,
            models,
        })
    }
}

fn apply_theme(theme: &Theme<'_>) {
    let choice = match std::env::var("RBS_THEME").as_deref() {
        Ok("dark") => 0,
        Ok("light") => 1,
        Ok("high-contrast") => 2,
        _ => -1,
    };
    theme.set_choice(choice);
}

fn edge(code: i32) -> Edge {
    match code {
        0 => Edge::Left,
        1 => Edge::Right,
        2 => Edge::Top,
        _ => Edge::Bottom,
    }
}

fn panel(id: &str) -> Option<PanelId> {
    PanelId::parse(id).ok()
}

/// Connect one window's `Shell` callbacks to the shared state.
fn install(g: &Shell<'_>, ctx: &Ctx) {
    macro_rules! on {
        ($name:ident, |$app:ident $(, $arg:ident : $ty:ty)*| $body:block) => {{
            let ctx = ctx.clone();
            g.$name(move |$($arg: $ty),*| ctx.update(move |$app: &mut App| $body));
        }};
    }
    on!(on_relayout, |app, window: i32, w: f32, h: f32| {
        app.set_area(window as usize, Rect::sized(w, h));
    });
    on!(on_activate_tab, |app, window: i32, stack: i32, tab: i32| {
        let c = LayoutCommand::ActivateTab {
            window: window as usize,
            stack: stack as usize,
            tab: tab as usize,
        };
        app.command(c, Origin::Pointer);
    });
    on!(on_close_panel, |app, id: slint::SharedString| {
        if let Some(id) = panel(&id) {
            app.command(LayoutCommand::ClosePanel(id), Origin::Pointer);
        }
    });
    on!(on_toggle_panel, |app, id: slint::SharedString| {
        if let Some(id) = panel(&id) {
            let c = if app.session.workspace().is_open(&id) {
                LayoutCommand::ClosePanel(id)
            } else {
                LayoutCommand::OpenPanel(id)
            };
            app.command(c, Origin::Command);
        }
    });
    on!(on_move_edge, |app,
                       id: slint::SharedString,
                       window: i32,
                       e: i32| {
        if let Some(id) = panel(&id) {
            let c = LayoutCommand::MoveToEdge {
                panel: id,
                window: window as usize,
                edge: edge(e),
            };
            app.command(c, Origin::Command);
        }
    });
    on!(on_move_next_stack, |app, id: slint::SharedString| {
        if let Some(id) = panel(&id)
            && let Some((w, s, _)) = app.session.workspace().find(&id)
        {
            let count = app.session.workspace().windows[w]
                .layout()
                .map_or(0, |l| l.stack_count());
            if count > 1 {
                let c = LayoutCommand::MoveToStack {
                    panel: id,
                    window: w,
                    stack: (s + 1) % count,
                };
                app.command(c, Origin::Command);
            }
        }
    });
    on!(on_float_panel, |app, id: slint::SharedString| {
        if let Some(id) = panel(&id) {
            app.command(LayoutCommand::Float(id), Origin::Command);
        }
    });
    on!(on_dock, |app, window: i32| {
        app.command(
            LayoutCommand::Dock {
                window: window as usize,
            },
            Origin::Command,
        );
    });
    on!(on_drag, |app, window: i32, handle: i32, position: f32| {
        app.drag(window as usize, handle as usize, position);
    });
    on!(on_drag_end, |app| {
        app.end_drag();
    });
    on!(on_nudge, |app, window: i32, handle: i32, delta: f32| {
        let window = window as usize;
        let c = LayoutCommand::Resize {
            window,
            area: app.area(window),
            handle: handle as usize,
            delta,
            group: None,
        };
        app.command(c, Origin::Command);
    });
    on!(on_switch_workspace, |app, name: slint::SharedString| {
        // Save first, so loading the workspace already shown reads the latest copy.
        app.flush();
        match app.store.load(&name) {
            Ok(ws) => app.command(LayoutCommand::Switch(ws), Origin::Command),
            Err(e) => app.error = Some(UiError::Other(e.to_string())),
        }
    });
    on!(on_save_workspace, |app| {
        app.persist_now();
        app.refresh_list();
    });
    on!(on_save_workspace_as, |app, name: slint::SharedString| {
        let current = app.session.workspace().clone();
        match app.store.save_as(&current, name.trim()) {
            Ok(ws) => {
                app.command(LayoutCommand::Switch(ws), Origin::Command);
                app.refresh_list();
            }
            Err(e) => app.error = Some(UiError::Other(e.to_string())),
        }
    });
    on!(on_restore_workspace, |app| {
        let name = app.session.workspace().name.clone();
        match app.store.restore_default(&name) {
            Ok(ws) => {
                app.command(LayoutCommand::Switch(ws), Origin::Command);
                app.refresh_list();
            }
            Err(e) => app.error = Some(UiError::Other(e.to_string())),
        }
    });
    on!(on_set_locked, |app, locked: bool| {
        app.command(LayoutCommand::SetLocked(locked), Origin::Command);
    });
    on!(on_undo, |app| {
        app.undo();
    });
    on!(on_redo, |app| {
        app.redo();
    });
    on!(on_toast_undo, |app| {
        if app.toast.is_some() {
            app.undo();
        }
    });
    on!(on_toast_dismiss, |app| {
        app.toast = None;
    });
    on!(on_dismiss_error, |app| {
        app.error = None;
    });
}

/// Connect one window's `Studio` callbacks to the studio and give it the shared models.
/// Drops the preview layer before the studio restarts (its frames go back first).
fn close_preview() {
    #[cfg(any(target_os = "macos", windows))]
    preview::close();
}

fn install_studio(g: &Studio<'_>, ctx: &Ctx) {
    if let Ok(app) = ctx.app.try_borrow() {
        app.studio.attach_models(g);
    }
    macro_rules! on {
        ($name:ident, |$app:ident $(, $arg:ident : $ty:ty)*| $body:block) => {{
            let ctx = ctx.clone();
            g.$name(move |$($arg: $ty),*| ctx.update(move |$app: &mut App| $body));
        }};
    }
    on!(on_list_targets, |app, kind: i32| {
        app.studio.list_targets(kind);
    });
    on!(on_add_source, |app, kind: i32, target: i32| {
        app.studio.add_source(kind, target);
    });
    on!(on_delete_source, |app, id: i32| {
        app.studio.delete_source(id);
    });
    on!(on_select_source, |app, id: i32| {
        app.studio.selected = id;
        app.studio.refresh_marks();
    });
    on!(on_preview_press, |app,
                           x: f32,
                           y: f32,
                           w: f32,
                           h: f32,
                           shift: bool,
                           no_snap: bool| {
        app.studio.preview_press([x, y], [w, h], shift, no_snap);
    });
    on!(on_preview_drag, |app, x: f32, y: f32| {
        app.studio.preview_drag([x, y]);
    });
    on!(on_preview_release, |app| {
        app.studio.preview_release();
    });
    on!(on_preview_nudge, |app, dx: i32, dy: i32| {
        app.studio.preview_nudge(dx as f32, dy as f32);
    });
    on!(on_preview_deselect, |app| {
        app.studio.selected = -1;
        app.studio.refresh_marks();
    });
    on!(on_move_source, |app, id: i32, up: bool| {
        app.studio.move_source(id, up);
    });
    on!(on_set_source_box, |app,
                            id: i32,
                            x: f32,
                            y: f32,
                            w: f32,
                            h: f32| {
        app.studio.set_source_box(id, x, y, w, h);
    });
    on!(on_undo_delete, |app| {
        app.studio.undo_delete();
    });
    on!(on_undo_edit, |app, back: bool| {
        app.studio.undo_edit(back);
    });
    on!(on_dismiss_deleted, |app| {
        app.studio.deleted.clear();
    });
    on!(on_reset_clip, |app, i: i32| {
        app.studio.reset_clip(i);
    });
    {
        let ctx = ctx.clone();
        g.on_open_settings(move || ctx.open_settings(SECTION_RECORDING));
    }
    {
        let ctx = ctx.clone();
        g.on_open_stream_settings(move || ctx.open_settings(SECTION_STREAM));
    }
    on!(on_record, |app| {
        app.studio.record();
    });
    on!(on_stop_recording, |app| {
        app.studio.stop_recording();
    });
    on!(on_set_folder, |app, text: slint::SharedString| {
        app.studio.set_folder(&text);
    });
    on!(on_set_format, |app, i: i32| {
        app.studio.set_format(i);
    });
    on!(on_set_encoding, |app, out: i32, field: i32, value: i32| {
        app.studio.set_encoding(out, field, value);
    });
    on!(on_go_live, |app| {
        app.studio.go_live();
    });
    on!(on_end_stream, |app| {
        app.studio.end_stream();
    });
    on!(on_set_server, |app, text: slint::SharedString| {
        app.studio.set_server(&text);
    });
    on!(on_server_edited, |app, text: slint::SharedString| {
        app.studio.server_edited(&text);
    });
    on!(on_save_key, |app, text: slint::SharedString| {
        app.studio.save_key(&text);
    });
    on!(on_remove_key, |app| {
        app.studio.remove_key();
    });
    on!(on_set_reconnect, |app, on: bool| {
        app.studio.set_reconnect(on);
    });
    on!(on_set_latency, |app, i: i32| {
        app.studio.set_latency(i);
    });
    on!(on_set_canvas_size, |app, i: i32| {
        app.studio.set_canvas_size(i, close_preview);
    });
    on!(on_set_canvas_rate, |app, i: i32| {
        app.studio.set_canvas_rate(i, close_preview);
    });
    on!(on_set_rc_enabled, |app, on: bool| {
        app.studio.set_remote_enabled(on);
    });
    on!(on_set_rc_port, |app, text: slint::SharedString| {
        app.studio.set_remote_port(&text);
    });
    on!(on_create_token, |app,
                          name: slint::SharedString,
                          access: i32| {
        app.studio.create_token(&name, access);
    });
    on!(on_revoke_token, |app, i: i32| {
        app.studio.revoke_token(i);
    });
    on!(on_dismiss_new_token, |app| {
        app.studio.dismiss_new_token();
    });
    on!(on_undo_revoke, |app| {
        app.studio.undo_revoke();
    });
    on!(on_set_rc_network, |app, on: bool| {
        app.studio.set_network(on);
    });
    on!(on_set_rc_remote_admin, |app, on: bool| {
        app.studio.set_remote_admin(on);
    });
    on!(
        on_rc_use_own,
        |app, cert: slint::SharedString, key: slint::SharedString| {
            app.studio.use_own_certificate(&cert, &key);
        }
    );
    on!(on_rc_use_generated, |app| {
        app.studio.use_generated_certificate();
    });
    on!(on_rc_new_key, |app| {
        app.studio.new_key();
    });
    // A popup opened or closed: the preview layer hides or shows at once.
    #[cfg(any(target_os = "macos", windows))]
    {
        let ctx = ctx.clone();
        g.on_overlays_changed(move || {
            if let Ok(app) = ctx.app.try_borrow() {
                preview::place(&app.main);
            }
        });
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let demo_live = std::env::args().any(|a| a == "--demo-live");
    slint::BackendSelector::new()
        .backend_name("winit".into())
        .renderer_name("skia".into())
        .select()?;

    let config = config::config_dir();
    // The stream key's store: read only when a stream starts (src/stream_key.rs).
    let keys = rbs_app::stream_key::system();
    let studio_config = config.clone();
    // The output profile and scene collection in use (ADR-0051); failed saves are
    // reported like other studio errors.
    let (user, collection) = rbs_app::user_session::open(
        &config,
        std::sync::Arc::new(|why| deliver(studio_host::Update::Error(why))),
    );
    let user_notes = user.notes.clone();
    let first_canvas = rbs_app::user_session::first_canvas(&collection);
    let autosave = user.collection_saver();
    let store = WorkspaceStore::new(config::workspace_dir(&config));
    let name = config::last_workspace(&config).unwrap_or_else(|| "Edit".to_owned());
    let mut error = None;
    let workspace = match store.load(&name) {
        Ok(w) => w,
        Err(e) => {
            error = Some(UiError::Other(e.to_string()));
            builtin::edit()
        }
    };
    let mut session = LayoutSession::new(workspace);
    if demo_live {
        session.set_live(LiveStatus {
            live: true,
            recording: true,
            elapsed_secs: 0,
            outputs: vec!["Twitch".into(), "Recording".into()],
        });
    }

    let main = MainWindow::new()?;
    apply_theme(&main.global::<Theme>());
    let main_models = DockModels::new();
    main.set_stacks(ModelRc::from(main_models.stacks.clone()));
    main.set_handles(ModelRc::from(main_models.handles.clone()));
    let ctx = Ctx {
        app: Rc::new(RefCell::new(App {
            session,
            store,
            config,
            workspaces: Vec::new(),
            main: main.clone_strong(),
            main_models,
            panels_model: Rc::new(VecModel::default()),
            workspaces_model: Rc::new(VecModel::default()),
            floats: Vec::new(),
            areas: Vec::new(),
            drag_group: None,
            next_group: 0,
            toast: None,
            toast_serial: 0,
            error,
            save_due: false,
            exiting: false,
            settings: None,
            demo_since: demo_live.then(Instant::now),
            studio: studio_ui::StudioUi::new(&studio_config, keys.as_ref(), user, first_canvas),
        })),
        queue: Rc::new(RefCell::new(Vec::new())),
        pending: Rc::new(Cell::new(false)),
        toast_timer: Rc::new(slint::Timer::default()),
        toast_shown: Rc::new(Cell::new(0)),
        save_timer: Rc::new(slint::Timer::default()),
        meter_timer: Rc::new(slint::Timer::default()),
        deleted_timer: Rc::new(slint::Timer::default()),
        deleted_shown: Rc::new(Cell::new(0)),
        live_timer: Rc::new(slint::Timer::default()),
    };
    install(&main.global::<Shell>(), &ctx);
    install_studio(&main.global::<Studio>(), &ctx);
    CTX.with(|c| *c.borrow_mut() = Some(ctx.clone()));
    // The studio: its own control thread (ADR-0041 decision 7), on the saved canvas.
    let studio_canvas = {
        let c = ctx.app.borrow().studio.canvas;
        let mut config = studio_host::HostConfig::canvas(c.size(), c.frame_rate());
        config.keys = keys;
        config.collection = Some(collection);
        config.autosave = autosave;
        config
    };
    match studio_host::StudioHost::spawn(
        studio_canvas,
        rbs_app::platform::adapters,
        || {
            // A hardware adapter, else a software one (a virtual machine, for example):
            // slow, but the app still works.
            let ctx = match rbs_gpu::GpuContext::new(&rbs_gpu::GpuRequest::default()) {
                Err(rbs_gpu::GpuError::NoAdapter) => {
                    rbs_gpu::GpuContext::new(&rbs_gpu::GpuRequest {
                        allow_software: true,
                        ..rbs_gpu::GpuRequest::default()
                    })
                }
                other => other,
            };
            ctx.map(std::sync::Arc::new)
                .map_err(|e| format!("no usable GPU: {e}"))
        },
        || {
            let mut engine = rbs_engine::Engine::new();
            engine.set_thread_policy(Some(std::sync::Arc::new(
                rbs_thread_os::OsThreadPolicy::new(),
            )));
            engine
        },
        deliver,
    ) {
        Ok(host) => ctx.update(move |app| {
            app.studio.host = Some(host);
            // Remote control, if the user turned it on (off by default: nothing starts).
            app.studio.sync_remote();
        }),
        Err(e) => ctx.update(move |app| {
            app.studio.state = 2;
            app.studio.failure = e.to_string();
        }),
    }
    ctx.update(App::refresh_list);
    // Entries that could not be read, or read-only mode: in the error bar once.
    if !user_notes.is_empty() {
        deliver(studio_host::Update::Error(user_notes.join("\n")));
    }

    // Closing the main window ends the app: floating windows close with it and
    // their closing is not a layout change.
    {
        let ctx = ctx.clone();
        main.window().on_close_requested(move || {
            if let Ok(mut app) = ctx.app.try_borrow_mut() {
                // Ending a stream cannot be undone: the frame asks first (U4).
                if app.studio.st_state != studio_ui::st_state::OFF {
                    app.main.global::<Shell>().set_quit_confirm(true);
                    return slint::CloseRequestResponse::KeepWindowShown;
                }
                app.exiting = true;
                if app.save_due {
                    app.persist_now();
                }
            }
            let _ = slint::quit_event_loop();
            slint::CloseRequestResponse::HideWindow
        });
    }
    {
        let ctx = ctx.clone();
        main.global::<Shell>().on_quit_keep(move || {
            if let Ok(app) = ctx.app.try_borrow() {
                app.main.global::<Shell>().set_quit_confirm(false);
            }
        });
    }
    {
        // Quitting ends the stream: the studio host's shutdown ends it cleanly.
        let ctx = ctx.clone();
        main.global::<Shell>().on_quit_end_stream(move || {
            if let Ok(mut app) = ctx.app.try_borrow_mut() {
                app.exiting = true;
                if app.save_due {
                    app.persist_now();
                }
                let _ = app.main.hide();
            }
            let _ = slint::quit_event_loop();
        });
    }

    main.run()?;
    // The layer's frames go back before the studio and its publisher stop.
    #[cfg(any(target_os = "macos", windows))]
    preview::close();
    if let Ok(mut app) = ctx.app.try_borrow_mut() {
        if app.save_due {
            app.persist_now();
        }
        // Disconnects remote control apps, then stops the studio and joins its thread.
        app.studio.stop_remote();
        app.studio.host = None;
        // The last changes reach the disk before the app ends.
        app.studio.user.flush();
    }
    CTX.with(|c| c.borrow_mut().take());
    Ok(())
}
