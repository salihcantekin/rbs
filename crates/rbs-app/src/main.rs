/// Row models of one window's dock area. They live as long as the window, so
/// unchanged rows keep their view instances (and keyboard focus).
struct DockModels {
    stacks: Rc<VecModel<StackData>>,
    handles: Rc<VecModel<HandleData>>,
}

impl DockModels {
    fn new() -> Self {
        DockModels {
            stacks: Rc::new(VecModel::default()),
            handles: Rc::new(VecModel::default()),
        }
    }

    fn update(&self, stacks: Vec<StackData>, handles: Vec<HandleData>) {
        let stacks = stacks
            .into_iter()
            .enumerate()
            .map(|(i, mut s)| {
                // Keep the old tab model when the tabs are the same, so the tab
                // views are not rebuilt.
                if let Some(old) = self.stacks.row_data(i)
                    && same_tabs(&old.tabs, &s.tabs)
                {
                    s.tabs = old.tabs;
                }
                s
            })
            .collect();
        set_rows(&self.stacks, stacks);
        set_rows(&self.handles, handles);
    }
}

fn same_tabs(a: &ModelRc<TabData>, b: &ModelRc<TabData>) -> bool {
    a.row_count() == b.row_count() && a.iter().zip(b.iter()).all(|(x, y)| x == y)
}

/// Replace rows that changed; rebuild only when the number of rows changes.
fn set_rows<T: Clone + PartialEq + 'static>(model: &VecModel<T>, rows: Vec<T>) {
    if model.row_count() != rows.len() {
        model.set_vec(rows);
        return;
    }
    for (i, row) in rows.into_iter().enumerate() {
        if model.row_data(i).as_ref() != Some(&row) {
            model.set_row_data(i, row);
        }
    }
}

