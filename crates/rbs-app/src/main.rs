/// The `Menus` global's models, shared by every window (`menu_bar`).
#[derive(Default)]
struct MenuModels {
    titles: Rc<VecModel<slint::SharedString>>,
    icons: Rc<VecModel<slint::Image>>,
    enabled: Rc<VecModel<bool>>,
    checked: Rc<VecModel<bool>>,
    choices: Rc<VecModel<ModelRc<MenuChoice>>>,
    /// The values shown, so an unchanged menu bar is not rebuilt.
    shown: Option<menu_bar::Values>,
}

impl MenuModels {
    fn update(&mut self, v: menu_bar::Values) {
        if self.shown.as_ref() == Some(&v) {
            return;
        }
        set_rows(
            &self.titles,
            v.titles.iter().map(|t| t.as_str().into()).collect(),
        );
        if self.shown.as_ref().map(|s| &s.icons) != Some(&v.icons) {
            set_rows(
                &self.icons,
                v.icons.iter().map(|n| icons::menu_image(n)).collect(),
            );
        }
        set_rows(&self.enabled, v.enabled.clone());
        set_rows(&self.checked, v.checked.clone());
        if self.shown.as_ref().map(|s| &s.choices) != Some(&v.choices) {
            let rows: Vec<ModelRc<MenuChoice>> = v
                .choices
                .iter()
                .map(|list| {
                    let items: Vec<MenuChoice> = list
                        .iter()
                        .map(|(title, id, checked)| MenuChoice {
                            title: title.as_str().into(),
                            id: id.as_str().into(),
                            checked: *checked,
                        })
                        .collect();
                    ModelRc::from(Rc::new(VecModel::from(items)))
                })
                .collect();
            self.choices.set_vec(rows);
        }
        self.shown = Some(v);
    }

    fn push(&self, g: &Menus<'_>) {
        g.set_titles(ModelRc::from(self.titles.clone()));
        g.set_icons(ModelRc::from(self.icons.clone()));
        g.set_enabled(ModelRc::from(self.enabled.clone()));
        g.set_checked(ModelRc::from(self.checked.clone()));
        g.set_choices(ModelRc::from(self.choices.clone()));
    }
}

impl App {
    /// Shows why an Output profile or Scene collection menu action did not work.
    fn library_done(&mut self, done: Result<(), String>) {
        if let Err(e) = done {
            self.error = Some(UiError::Other(e));
        }
    }

    fn default_area(&self, window: usize) -> Rect {
        let t = self.main.global::<Tokens>();
        if window == 0 {
            Rect::sized(t.get_size_window_w(), t.get_size_window_h())
        } else {
            Rect::sized(t.get_size_floating_w(), t.get_size_floating_h())
        }
    }

    fn area(&self, window: usize) -> Rect {
        self.areas
            .iter()
            .find(|(w, _)| *w == window)
            .map_or_else(|| self.default_area(window), |(_, r)| *r)
    }

    fn set_area(&mut self, window: usize, r: Rect) {
        match self.areas.iter_mut().find(|(w, _)| *w == window) {
            Some(entry) => entry.1 = r,
            None => self.areas.push((window, r)),
        }
    }

    fn refresh_list(&mut self) {
        match self.store.list() {
            Ok(l) => {
                self.workspaces = l
                    .workspaces
                    .into_iter()
                    .map(|w| (w.name, w.built_in))
                    .collect();
                if let Some((path, e)) = l.problems.first() {
                    self.error = Some(UiError::Other(format!("{}: {e}", path.display())));
                }
            }
            Err(e) => self.error = Some(UiError::Other(e.to_string())),
        }
    }

    /// Save the current workspace now and remember it for the next start.
    fn persist_now(&mut self) {
        self.save_due = false;
        let ws = self.session.workspace();
        let result = self.store.save(ws).map(|_| ()).and_then(|()| {
            config::set_last_workspace(&self.config, &ws.name).map_err(StoreError::Io)
        });
        if let Err(e) = result {
            self.error = Some(UiError::Other(e.to_string()));
        }
    }

    fn command(&mut self, c: LayoutCommand, origin: Origin) {
        // Leaving a workspace: write its pending changes first, because the
        // debounced save only ever writes the current workspace.
        if matches!(c, LayoutCommand::Switch(_)) {
            self.flush();
        }
        match self.session.apply(c, origin) {
            Ok(toast) => {
                // A maximized panel that was closed or switched away is not any more.
                let ws = self.session.workspace();
                if self.maximized.as_ref().is_some_and(|m| !ws.is_open(m)) {
                    self.maximized = None;
                }
                // A toast's undo always means the latest change, so any later
                // change replaces or removes it.
                self.set_toast(toast);
                self.changed();
            }
            Err(CommandError::Locked) => self.error = Some(UiError::Locked),
            Err(e) => self.error = Some(UiError::Other(e.to_string())),
        }
    }

    fn set_toast(&mut self, toast: Option<Toast>) {
        if toast.is_some() {
            self.toast_serial += 1;
        }
        self.toast = toast;
    }

    /// After any layout change: save soon. Window sizes are re-keyed in
    /// `sync_floats`, which knows which OS window shows which workspace window.
    fn changed(&mut self) {
        self.save_due = true;
    }

    /// Write pending changes now. Called before anything that may leave the
    /// current workspace or reload it from disk (switch, undo, redo).
    fn flush(&mut self) {
        if self.save_due {
            self.persist_now();
        }
    }

    /// Loads the named workspace and switches to it.
    fn switch_workspace(&mut self, name: &str) {
        // Save first, so loading the workspace already shown reads the latest copy.
        self.flush();
        match self.store.load(name) {
            Ok(ws) => self.command(LayoutCommand::Switch(ws), Origin::Command),
            Err(e) => self.error = Some(UiError::Other(e.to_string())),
        }
    }

    /// The shell's state as the command registry reads it.
    fn shown(&self) -> menu_bar::Shown<'_> {
        menu_bar::Shown {
            workspace: self.session.workspace(),
            workspaces: &self.workspaces,
            studio: &self.studio,
            maximized: self.maximized.as_ref(),
            camera: self.vcam.shown(),
            panels: view::panel_entries(self.session.workspace())
                .into_iter()
                .map(|p| (p.title.into(), p.id.into(), p.open))
                .collect(),
        }
    }

    /// Runs a command registry id from the menu bar or an app-scope shortcut
    /// (ADR-0050, ADR-0060), with the menu's confirmations.
    fn run_command(&mut self, id: &str) {
        self.run_command_as(id, true);
    }

    /// Runs a command registry id; `confirm` false acts as a control surface does
    /// (`ui.command.run`, a global shortcut): ending the stream does not ask.
    fn run_command_as(&mut self, id: &str, confirm: bool) {
        use menu_bar::Run;
        let Some(run) = menu_bar::run(id, &self.shown()) else {
            return;
        };
        match run {
            Run::UndoEdit(back) => self.studio.undo_edit(back),
            Run::Workspace(name) => self.switch_workspace(&name),
            Run::Panel(id) => {
                if let Some(id) = panel(&id) {
                    self.command(LayoutCommand::OpenPanel(id), Origin::Command);
                }
            }
            Run::Profile(id) => {
                let done = self.studio.switch_profile(&id);
                self.library_done(done);
            }
            Run::Collection(id) => {
                let done = self.studio.switch_collection(&id, close_preview);
                self.library_done(done);
            }
            Run::Scene(id) => self.studio.switch_scene(id),
            Run::Layout(c) => self.command(c, Origin::Command),
            Run::Maximize(id, on) => self.maximized = on.then_some(id),
            Run::AddSource(kind) => self.ask_add_source(kind),
            Run::StudioMode(on) => self.studio.set_studio_mode(on),
            Run::Transition => self.studio.transition(),
            Run::AddScene => self.studio.add_scene(),
            Run::RenameScene(id, Some(name)) => self.studio.rename_scene(id, &name),
            // Asking for a name needs someone at the window: not from a control
            // surface or a global shortcut (`ui.command.run` answers `invalid_params`).
            Run::RenameScene(_, None) | Run::RenameSource(_, None) if !confirm => {}
            Run::RenameScene(id, None) => self.ask_rename(id, true),
            Run::RemoveScene(id) => self.studio.remove_scene(id),
            Run::RenameSource(id, Some(name)) => self.studio.rename_source(id, &name),
            Run::RenameSource(id, None) => self.ask_rename(id, false),
            Run::DeleteSource(id) => self.studio.delete_source(id),
            Run::RemoveFromScene(id) => self.studio.remove_from_scene(id),
            Run::SourceVisible(id, on) => self.studio.set_source_visible(id, on),
            Run::SourceLocked(id, on) => self.studio.set_source_locked(id, on),
            Run::SourceMuted(id, on) => self.studio.set_source_muted(id, on),
            Run::SourceMixerHidden(id, on) => self.studio.set_source_mixer_hidden(id, on),
            Run::MixerBulk(bulk) => match bulk {
                menu_bar::MixerBulk::HideAll => self.studio.hide_in_mixer(true, false),
                menu_bar::MixerBulk::HideMuted => self.studio.hide_in_mixer(true, true),
                menu_bar::MixerBulk::ShowAll => self.studio.hide_in_mixer(false, false),
            },
            Run::GoLive => self.studio.go_live(),
            Run::AskEndStream if confirm => self.confirm_end = true,
            Run::AskEndStream => self.studio.end_stream(),
            Run::Record => self.studio.record(),
            Run::StopRecording => self.studio.stop_recording(),
            Run::VirtualCamera(on) => vcam_page::send(self, on),
            // Needs the look and the Appearance page, which the next sync has.
            Run::ReloadThemes => self.reload_themes = true,
            // Making the window needs the shell's context, which the next sync has.
            Run::OpenSettings(section) => self.open_settings = Some(section),
            Run::OpenAppMenu => self.open_app_menu = true,
        }
    }

    /// Starts the name field of a scene's (`scene`) or source's row: Rename from a menu
    /// or a shortcut. The row's panel is opened first.
    fn ask_rename(&mut self, id: i32, scene: bool) {
        let name = if scene { "rbs.scenes" } else { "rbs.sources" };
        if let Some(p) = panel(name) {
            self.command(LayoutCommand::OpenPanel(p), Origin::Command);
        }
        // The id says which row; the count makes each ask a change, also for the same
        // row twice. A row made later (its panel was closed) checks the id when made.
        let ask = |g: Studio<'_>| {
            if scene {
                g.set_renaming_scene(id);
                g.set_rename_scene_asked(g.get_rename_scene_asked() + 1);
            } else {
                g.set_renaming_source(id);
                g.set_rename_source_asked(g.get_rename_source_asked() + 1);
            }
        };
        ask(self.main.global::<Studio>());
        for f in &self.floats {
            ask(f.window.global::<Studio>());
        }
    }

    /// The items of a context menu (`ui/context_menu.slint`): `context` names the
    /// element, `target` what was right-clicked. A source's row or picture becomes
    /// the selection, as a click would make it.
    fn context_items(&mut self, context: &str, target: &str) -> Vec<context_menu::Item> {
        use rbs_ui::command::Context;
        let Some(mut target) = context_menu::target(target) else {
            return Vec::new();
        };
        let param = |t: &[(String, String)], k: &str| {
            t.iter().find(|(key, _)| key == k).map(|(_, v)| v.clone())
        };
        let context = match context {
            // The picture: the source under the pointer, else the panel's own menu.
            "preview" => {
                let num = |k| param(&target, k).and_then(|v| v.parse::<f32>().ok());
                let (Some(x), Some(y), Some(w), Some(h)) = (num("x"), num("y"), num("w"), num("h"))
                else {
                    return Vec::new();
                };
                match self.studio.preview_source_at([x, y], [w, h]) {
                    Some(id) => {
                        let Some(f) = self.studio.source_facts(Some(&id.to_string()), None) else {
                            return Vec::new();
                        };
                        target = vec![
                            ("item".to_owned(), f.item.to_string()),
                            ("source".to_owned(), f.id.to_string()),
                        ];
                        Context::Source
                    }
                    None => {
                        target.retain(|(k, _)| k == "id");
                        Context::Preview
                    }
                }
            }
            "source" => {
                let Some(f) =
                    param(&target, "source").and_then(|v| self.studio.source_facts(Some(&v), None))
                else {
                    return Vec::new();
                };
                self.studio.selected = f.id;
                self.studio.refresh_marks();
                target.push(("item".to_owned(), f.item.to_string()));
                Context::Source
            }
            other => match Context::parse(other) {
                Some(c) => c,
                None => return Vec::new(),
            },
        };
        context_menu::items(context, &target, &self.shown())
    }

    /// Opens the Sources panel's Add source menu, at the list of `kind`'s targets when
    /// given (toolbar, Source menu). The panel is opened or expanded first.
    fn ask_add_source(&mut self, kind: Option<i32>) {
        let Some(sources) = panel("rbs.sources") else {
            return;
        };
        self.command(LayoutCommand::OpenPanel(sources.clone()), Origin::Command);
        let ws = self.session.workspace();
        let collapsed = ws
            .find(&sources)
            .and_then(|(w, s, _)| ws.windows[w].stack(s))
            .is_some_and(|t| t.collapsed);
        if collapsed {
            let c = LayoutCommand::SetCollapsed {
                panel: sources.clone(),
                collapsed: false,
            };
            self.command(c, Origin::Command);
        }
        // A maximized panel that is not Sources would cover the menu.
        if self.maximized.as_ref().is_some_and(|m| *m != sources) {
            self.maximized = None;
        }
        if let Some(code) = kind {
            self.studio.list_targets(code);
        }
        let ask = |g: Studio<'_>| {
            g.set_picker_kind(kind.unwrap_or(-1));
            g.set_add_source_asked(g.get_add_source_asked() + 1);
        };
        ask(self.main.global::<Studio>());
        for f in &self.floats {
            ask(f.window.global::<Studio>());
        }
    }

    fn undo(&mut self) {
        self.flush();
        if self.session.undo() {
            self.toast = None;
            self.changed();
        }
    }

    fn redo(&mut self) {
        self.flush();
        if self.session.redo() {
            self.toast = None;
            self.changed();
        }
    }

    fn drag(&mut self, window: usize, handle: usize, position: f32) {
        let area = self.area(window);
        let Some(h) = self
            .session
            .workspace()
            .windows
            .get(window)
            .and_then(|w| {
                w.flatten_in(area, self.studio.studio_mode)
                    .handles
                    .into_iter()
                    .nth(handle)
            })
            .map(|h| h.handle)
        else {
            return;
        };
        let current = match h.axis {
            Axis::Horizontal => h.rect.x,
            Axis::Vertical => h.rect.y,
        };
        let delta = position - current;
        if delta.abs() < 0.5 {
            return;
        }
        let group = match self.drag_group {
            Some(g) => g,
            None => {
                self.next_group += 1;
                self.drag_group = Some(self.next_group);
                self.next_group
            }
        };
        let c = LayoutCommand::Resize {
            window,
            area,
            handle,
            delta,
            group: Some(group),
            studio_mode: self.studio.studio_mode,
        };
        self.command(c, Origin::Pointer);
    }

    /// Where panel `panel` dragged to `(x, y)` in window `window`'s dock area would go.
    fn drop_at(&self, window: usize, panel: &PanelId, x: f32, y: f32) -> Option<DropTarget> {
        let area = self.area(window);
        let w = self.session.workspace().windows.get(window)?;
        let flat = view::shown_flat(w, area, self.maximized.as_ref(), self.studio.studio_mode);
        drop_target(&flat, area, panel, x, y)
    }

    /// A tab is dragged over window `window`'s dock area: show where it would go.
    fn drag_over(&mut self, window: usize, panel: Option<PanelId>, x: f32, y: f32) {
        let guide = panel
            .and_then(|p| self.drop_at(window, &p, x, y))
            .map(|t| (window, t.guide));
        self.show_drop_guide(guide);
    }

    /// A tab is dropped on window `window`'s dock area.
    fn drag_drop(&mut self, window: usize, panel: Option<PanelId>, x: f32, y: f32) {
        self.show_drop_guide(None);
        let Some(panel) = panel else { return };
        let Some(t) = self.drop_at(window, &panel, x, y) else {
            return;
        };
        let c = match t.place {
            DropPlace::Into(stack) => LayoutCommand::MoveToStack {
                panel,
                window,
                stack,
            },
            DropPlace::Beside(stack, edge) => LayoutCommand::MoveBeside {
                panel,
                window,
                stack,
                edge,
            },
            DropPlace::WindowEdge(edge) => LayoutCommand::MoveToEdge {
                panel,
                window,
                edge,
            },
        };
        self.command(c, Origin::Pointer);
    }

    fn show_drop_guide(&mut self, guide: Option<(usize, Rect)>) {
        if guide == self.drop_guide {
            return;
        }
        self.drop_guide = guide;
        let set = |s: Shell<'_>| match guide {
            Some((w, r)) => {
                s.set_drop_window(w as i32);
                s.set_drop_guide(Cover {
                    x: r.x,
                    y: r.y,
                    width: r.w,
                    height: r.h,
                });
            }
            None => {
                s.set_drop_window(-1);
                s.set_drop_open(false);
            }
        };
        set(self.main.global::<Shell>());
        for f in &self.floats {
            set(f.window.global::<Shell>());
        }
    }

    fn end_drag(&mut self) {
        if self.drag_group.take().is_some() {
            self.session.end_group();
        }
    }
}

type Op = Box<dyn FnOnce(&mut App)>;

#[derive(Clone)]
struct Ctx {
    app: Rc<RefCell<App>>,
    /// The token file every window gets when it opens (`look`).
    look: Rc<RefCell<Option<look::Look>>>,
    /// Settings › Appearance (ADR-0057).
    page: Rc<RefCell<appearance_page::Page>>,
    /// Shortcuts: the keymap, global shortcuts and Settings › Shortcuts (ADR-0060).
    keys: Rc<RefCell<shortcuts_page::Keys>>,
    /// Changes asked for while the state was borrowed; applied before the next sync.
    queue: Rc<RefCell<Vec<Op>>>,
    pending: Rc<Cell<bool>>,
    /// Dismisses a toast after [`TOAST_TIME`]; runs only while a toast is shown.
    toast_timer: Rc<slint::Timer>,
    toast_shown: Rc<Cell<u64>>,
    /// Writes the layout [`SAVE_DELAY`] after the last change.
    save_timer: Rc<slint::Timer>,
    /// Refreshes the meters; runs only while the Mixer shows audio sources (U5, U16).
    meter_timer: Rc<slint::Timer>,
    /// Dismisses the "deleted" toast after [`TOAST_TIME`].
    deleted_timer: Rc<slint::Timer>,
    deleted_shown: Rc<Cell<u64>>,
    /// Ticks the live duration once a second while live or recording.
    live_timer: Rc<slint::Timer>,
}

/// Shows the Settings window. The only place that does, so every way to open Settings
/// (toolbar gear, RBS menu, shortcut, control API) lands centred on the main window.
/// A window that is already on screen stays where the user put it.
fn present_settings(w: &SettingsWindow, app: &App) {
    if w.window().is_visible() {
        let _ = w.show();
        return;
    }
    let t = w.global::<Tokens>();
    let size = slint::LogicalSize::new(t.get_size_settings_w(), t.get_size_settings_h());
    let _ = window_place::show_centred(w, &app.main, size, app.hidden);
}

/// Sections of the Settings window (`SettingsWindow.section`).
const SECTION_RECORDING: i32 = 1;
const SECTION_STREAM: i32 = 2;
const SECTION_GENERAL: i32 = 4;
const SECTION_APPEARANCE: i32 = 5;
const SECTION_SHORTCUTS: i32 = 6;
const SECTION_VIRTUAL_CAMERA: i32 = 8;

thread_local! {
    /// The shell's context, for updates the studio's control thread hands to the UI
    /// thread (`slint::invoke_from_event_loop` takes only `Send` closures).
    static CTX: RefCell<Option<Ctx>> = const { RefCell::new(None) };
    /// A hidden main window can be brought back (ADR-0056 decision 6): set once the
    /// platform's way back is in place.
    static WAY_BACK: Cell<bool> = const { Cell::new(false) };
}

/// Hands an update from the studio's control thread to the UI thread.
fn deliver(u: studio_host::Update) {
    let _ = entry::invoke(move || {
        let ctx = CTX.with(|c| c.borrow().clone());
        if let Some(ctx) = ctx {
            ctx.studio_update(u);
        }
    });
}

/// Shows a caught panic in the error bar (ADR-0055 decision 2): at most once every few
/// seconds, so a panic that repeats on every tick cannot flood the event loop.
fn show_caught() {
    thread_local! {
        static SHOWN: Cell<Option<Instant>> = const { Cell::new(None) };
    }
    let now = Instant::now();
    if SHOWN.with(|s| {
        s.get()
            .is_some_and(|t| now.duration_since(t) < CAUGHT_QUIET)
    }) {
        return;
    }
    SHOWN.with(|s| s.set(Some(now)));
    // Not through `Ctx::update` or the guarded helpers: a panic while showing it must
    // not report itself again.
    #[allow(clippy::disallowed_methods)]
    let _ = slint::invoke_from_event_loop(|| {
        let _ = rbs_crash::contain(|| {
            let ctx = CTX.with(|c| c.borrow().clone());
            if let Some(ctx) = ctx {
                if let Ok(mut app) = ctx.app.try_borrow_mut() {
                    app.error = Some(UiError::Notice(rbs_crash::CAUGHT_TEXT.into()));
                }
                ctx.sync();
            }
        });
    });
}

impl Ctx {
    /// Change the state, then update the views once on the next event loop turn.
    /// Views are never updated from inside a callback, so creating or hiding
    /// windows cannot re-enter borrowed state.
    fn update(&self, f: impl FnOnce(&mut App) + 'static) {
        match self.app.try_borrow_mut() {
            Ok(mut app) => entry::guard(|| f(&mut app)),
            Err(_) => self.queue.borrow_mut().push(Box::new(f)),
        }
        if !self.pending.replace(true) {
            let ctx = self.clone();
            entry::single_shot(Duration::ZERO, move || {
                ctx.pending.set(false);
                ctx.sync();
            });
        }
    }

    /// Lays out `window`'s panels for its current size at once, and places the preview
    /// layer over them. Creates and hides no window, so it is safe inside a callback;
    /// the full update still follows on the next event loop turn.
    fn relayout_now(&self, window: usize) {
        let Ok(mut app) = self.app.try_borrow_mut() else {
            return;
        };
        if app.hidden || app.exiting {
            return;
        }
        let Some(ws_window) = app.session.workspace().windows.get(window) else {
            return;
        };
        let (stacks, handles, rail) = view::window_view(
            window,
            ws_window,
            app.area(window),
            app.maximized.as_ref(),
            app.studio.studio_mode,
        );
        if window == 0 {
            app.main_models.update(stacks, handles);
            if app.main.get_rail() != rail {
                app.main.set_rail(rail);
            }
            self.sync_studio(&mut app);
        } else if let Some(slot) = app.floats.iter().find(|f| f.index == Some(window)) {
            slot.models.update(stacks, handles);
        }
    }

    /// Update only the live duration (the 1 Hz tick while live or recording).
    fn live_tick(&self) {
        let Ok(mut app) = self.app.try_borrow_mut() else {
            return;
        };
        // Since going live while live, else since the recording started.
        let elapsed = match (
            app.demo_since,
            app.studio.streaming_for(),
            app.studio.recording_for(),
        ) {
            (Some(since), _, _) => since.elapsed(),
            (None, Some((d, _, _)), _) | (None, None, Some((d, _))) => d,
            (None, None, None) => return,
        };
        let mut live = app.session.live().clone();
        live.elapsed_secs = elapsed.as_secs();
        let text: slint::SharedString = live.duration_text().into();
        app.session.set_live(live);
        // The tray tooltip's time, only while no window shows it (ADR-0056 decision 5).
        #[cfg(windows)]
        if app.hidden {
            Self::sync_tray_text(&mut app);
        }
        app.main.global::<Shell>().set_live_duration(text.clone());
        for f in &app.floats {
            f.window.global::<Shell>().set_live_duration(text.clone());
        }
    }

    /// Applies an update from the studio.
    fn studio_update(&self, u: studio_host::Update) {
        let ctx = self.clone();
        self.update(move |app| {
            let applied = app.studio.apply(u);
            if let Some(e) = applied.error {
                // A caught panic on the studio's thread reads as a notice, not as an
                // action that failed (ADR-0055).
                app.error = Some(if e == rbs_crash::CAUGHT_TEXT {
                    UiError::Notice(e)
                } else {
                    UiError::Other(e)
                });
            }
            if let Some(endpoint) = applied.preview {
                app.preview_endpoint = Some(endpoint.clone());
                // A hidden window connects when it shows again (ADR-0056 decision 5).
                if !app.hidden {
                    ctx.connect_preview(endpoint);
                }
            }
            // Entering studio mode opens a closed Preview panel where it opens by
            // default, the only layout change studio mode makes (ADR-0061).
            if applied.studio_mode_started
                && let Some(p) = panel("rbs.preview")
                && !app.session.workspace().is_open(&p)
            {
                app.command(LayoutCommand::OpenPanel(p), Origin::Command);
            }
            if let Some(endpoint) = applied.scene_preview {
                #[cfg(any(target_os = "macos", windows))]
                preview::close_one(preview::Picture::Scene);
                app.scene_preview_endpoint = endpoint.clone();
                if let Some(endpoint) = endpoint
                    && !app.hidden
                {
                    ctx.connect_scene_preview(endpoint);
                }
            }
            if let Some(camera) = applied.camera {
                app.vcam.sending(camera);
            }
            if let Some((collection, id)) = applied.switch {
                let done = if collection {
                    app.studio.switch_collection(&id, close_preview)
                } else {
                    app.studio.switch_profile(&id)
                };
                // Answers the host, also when the switch was refused.
                app.studio.refresh_library();
                app.library_done(done);
            }
        });
    }

    #[cfg(any(target_os = "macos", windows))]
    fn connect_preview(&self, endpoint: rbs_gpu::share::PreviewEndpoint) {
        preview::connect(preview::Picture::Program, endpoint, |ok| {
            let ctx = CTX.with(|c| c.borrow().clone());
            if let Some(ctx) = ctx {
                ctx.update(move |app| {
                    app.studio.preview_ready = ok;
                    app.studio.preview_failed = !ok;
                });
            }
        });
    }

    #[cfg(not(any(target_os = "macos", windows)))]
    fn connect_preview(&self, _endpoint: rbs_gpu::share::PreviewEndpoint) {}

    /// The preview scene's picture in studio mode (ADR-0061; macOS only for now).
    #[cfg(target_os = "macos")]
    fn connect_scene_preview(&self, endpoint: rbs_gpu::share::PreviewEndpoint) {
        preview::connect(preview::Picture::Scene, endpoint, |ok| {
            let ctx = CTX.with(|c| c.borrow().clone());
            if let Some(ctx) = ctx {
                ctx.update(move |app| {
                    app.studio.scene_preview_ready = ok;
                    app.studio.scene_preview_failed = !ok;
                });
            }
        });
    }

    #[cfg(not(target_os = "macos"))]
    fn connect_scene_preview(&self, _endpoint: rbs_gpu::share::PreviewEndpoint) {}

    /// Shows the Settings window at `section`, made on first use and kept until it is
    /// closed.
    fn open_settings(&self, section: i32) {
        let ctx = self.clone();
        self.update(move |app| {
            app.studio.settings_opened();
            if let Some(w) = &app.settings {
                w.set_section(section);
                present_settings(w, app);
                if section == SECTION_APPEARANCE {
                    appearance_page::opened(&ctx, app);
                }
                if section == SECTION_SHORTCUTS {
                    shortcuts_page::opened(&ctx, app);
                }
                if section == SECTION_VIRTUAL_CAMERA {
                    vcam_page::opened(app);
                }
                return;
            }
            let Ok(w) = SettingsWindow::new() else {
                app.error = Some(UiError::Other(
                    "The settings window cannot be opened.".into(),
                ));
                return;
            };
            look::apply(
                &w.global::<Theme>(),
                &w.global::<Tokens>(),
                ctx.look.borrow().as_ref(),
            );
            install_studio(&w.global::<Studio>(), &ctx);
            install_sections(&w.global::<Sections>(), &ctx);
            // `install_studio` cannot borrow the app here (this runs inside an update):
            // the shared models (the access token list) are attached directly.
            app.studio.attach_models(&w.global::<Studio>());
            let c = ctx.clone();
            entry::on_close_requested(w.window(), move || {
                shortcuts_page::closed(&c);
                c.update(|app| {
                    app.settings = None;
                    app.studio.settings_closed();
                });
                slint::CloseRequestResponse::HideWindow
            });
            // Escape: hidden and dropped as by the close button. The strong handle
            // keeps the window alive until the callback returns.
            let weak = w.as_weak();
            let c = ctx.clone();
            w.on_dismiss(move || {
                entry::guard(|| {
                    let Some(w) = weak.upgrade() else {
                        return;
                    };
                    let _ = w.hide();
                    shortcuts_page::closed(&c);
                    c.update(|app| {
                        app.settings = None;
                        app.studio.settings_closed();
                    });
                });
            });
            appearance_page::install(&w.global::<Appearance>(), &ctx);
            shortcuts_page::install(&w.global::<Shortcuts>(), &ctx);
            vcam_page::install(&w.global::<VirtualCamera>(), &ctx);
            let c = ctx.clone();
            w.on_section_shown(move |s| {
                if s == SECTION_VIRTUAL_CAMERA {
                    c.update(vcam_page::opened);
                }
                if s == SECTION_APPEARANCE {
                    let ctx = c.clone();
                    c.update(move |app| appearance_page::opened(&ctx, app));
                }
                if s == SECTION_SHORTCUTS {
                    let ctx = c.clone();
                    c.update(move |app| shortcuts_page::opened(&ctx, app));
                } else {
                    shortcuts_page::closed(&c);
                }
            });
            w.set_section(section);
            present_settings(&w, app);
            app.settings = Some(w);
            if section == SECTION_APPEARANCE {
                appearance_page::opened(&ctx, app);
            }
            if section == SECTION_SHORTCUTS {
                shortcuts_page::opened(&ctx, app);
            }
            if section == SECTION_VIRTUAL_CAMERA {
                vcam_page::opened(app);
            }
        });
    }

    /// One meter refresh (the timer runs only while the Mixer shows meters).
    fn meter_tick(&self) {
        if let Ok(mut app) = self.app.try_borrow_mut() {
            app.studio.tick_meters();
        }
    }

    /// Where the studio's panels are and what they show; starts and stops the meter
    /// timer and places the preview layer.
    /// The live status from the studio, and the 1 Hz duration tick while live or
    /// recording.
    fn sync_live(&self, app: &mut App) {
        // The live indicator follows the stream and the recording.
        if app.demo_since.is_none() {
            let live = match (app.studio.streaming_for(), app.studio.recording_for()) {
                (Some((d, host, connected)), rec) => LiveStatus {
                    live: true,
                    recording: rec.is_some(),
                    elapsed_secs: d.as_secs(),
                    outputs: std::iter::once(if connected {
                        host
                    } else {
                        format!("{host} not connected")
                    })
                    .chain(rec.map(|(_, file)| file))
                    .collect(),
                    camera: app.vcam.is_sending(),
                },
                (None, Some((d, file))) => LiveStatus {
                    live: false,
                    recording: true,
                    elapsed_secs: d.as_secs(),
                    outputs: vec![file],
                    camera: app.vcam.is_sending(),
                },
                (None, None) => LiveStatus {
                    camera: app.vcam.is_sending(),
                    ..LiveStatus::default()
                },
            };
            if *app.session.live() != live {
                app.session.set_live(live);
            }
        }
        // One tick a second while live or recording, none otherwise (ADR-0013).
        if app.session.live().is_active() {
            if !self.live_timer.running() {
                let ctx = self.clone();
                entry::start(
                    &self.live_timer,
                    slint::TimerMode::Repeated,
                    Duration::from_secs(1),
                    move || ctx.live_tick(),
                );
            }
        } else {
            self.live_timer.stop();
        }
    }

    fn sync_studio(&self, app: &mut App) {
        // A window made since the last sync may have asked while the app was busy and
        // kept a default: a new number makes every window ask again.
        let windows = 1 + app.floats.len() + usize::from(app.settings.is_some());
        if app.sections_shown != app.session.workspace().closed_sections
            || app.sections_windows != windows
        {
            app.sections_shown = app.session.workspace().closed_sections.clone();
            app.sections_windows = windows;
            app.sections_rev += 1;
        }
        let rev = app.sections_rev;
        app.main.global::<Sections>().set_rev(rev);
        for f in &app.floats {
            f.window.global::<Sections>().set_rev(rev);
        }
        if let Some(w) = &app.settings {
            w.global::<Sections>().set_rev(rev);
        }
        let t = app.main.global::<Tokens>();
        // A panel card's header is `size.control.lg` high, then a divider line.
        let bar = t.get_size_control_lg() + t.get_size_border();
        let border = t.get_size_border();
        let (ox, oy) = app.main_origin;
        let in_main = |id: &str| {
            studio_ui::active_content(&app.main_models.stacks, id, bar, border)
                .map(|[x, y, w, h]| [x + ox, y + oy, w, h])
        };
        let float_has = |id: &str| {
            app.floats
                .iter()
                .any(|f| studio_ui::active_content(&f.models.stacks, id, bar, border).is_some())
        };
        // Without studio mode Program and Preview both show the scene on air; the picture
        // goes to Program when it is shown, else to Preview. In studio mode Program shows
        // the scene on air and Preview the preview scene, which is edited (ADR-0061).
        let studio_mode = app.studio.studio_mode;
        let panel = if studio_mode {
            "rbs.preview"
        } else if in_main("rbs.program").is_some() || float_has("rbs.program") {
            "rbs.program"
        } else {
            "rbs.preview"
        };
        let program_panel = if studio_mode { "rbs.program" } else { panel };
        let picture_main = in_main(program_panel);
        let scene_main = if studio_mode {
            in_main("rbs.preview")
        } else {
            None
        };
        let edit_main = if studio_mode {
            scene_main
        } else {
            picture_main
        };
        if let Some([_, _, w, h]) = edit_main {
            app.studio.set_picture_size(w, h);
        }
        let mixer_shown = in_main("rbs.mixer").is_some() || float_has("rbs.mixer");
        use studio_ui::preview_state as ps;
        let s = &app.studio;
        let state = match s.state {
            0 => ps::STARTING,
            2 => ps::STOPPED,
            _ if !s.preview_offered => ps::NO_PLATFORM,
            _ if s.preview_failed => ps::NO_SESSION,
            _ if picture_main.is_none() && float_has(program_panel) => ps::OTHER_WINDOW,
            _ if s.preview_ready => ps::SHOWN,
            _ => ps::STARTING,
        };
        let scene_state = match s.state {
            0 => ps::STARTING,
            2 => ps::STOPPED,
            _ if !s.preview_offered || !cfg!(target_os = "macos") => ps::NO_PLATFORM,
            _ if s.scene_preview_failed => ps::NO_SESSION,
            _ if scene_main.is_none() && float_has("rbs.preview") => ps::OTHER_WINDOW,
            _ if s.scene_preview_ready => ps::SHOWN,
            _ => ps::STARTING,
        };
        let running = s.state == 1;
        s.push(&app.main.global::<Studio>(), state, scene_state, panel);
        app.vcam.push_live(&app.main.global::<Studio>(), running);
        for f in &app.floats {
            s.push(&f.window.global::<Studio>(), state, scene_state, panel);
            app.vcam.push_live(&f.window.global::<Studio>(), running);
        }
        if let Some(w) = &app.settings {
            s.push(&w.global::<Studio>(), state, scene_state, panel);
        }

        if mixer_shown && s.has_meters() {
            if !self.meter_timer.running() {
                let ctx = self.clone();
                entry::start(
                    &self.meter_timer,
                    slint::TimerMode::Repeated,
                    studio_ui::METER_PERIOD,
                    move || ctx.meter_tick(),
                );
            }
        } else {
            self.meter_timer.stop();
        }

        if !s.deleted.is_empty() {
            if self.deleted_shown.get() != s.deleted_serial || !self.deleted_timer.running() {
                self.deleted_shown.set(s.deleted_serial);
                let ctx = self.clone();
                entry::start(
                    &self.deleted_timer,
                    slint::TimerMode::SingleShot,
                    TOAST_TIME,
                    move || {
                        ctx.update(|app| app.studio.deleted.clear());
                    },
                );
            }
        } else {
            self.deleted_timer.stop();
        }

        #[cfg(any(target_os = "macos", windows))]
        {
            use preview::Picture;
            preview::set_area(Picture::Program, picture_main);
            preview::set_area(Picture::Scene, scene_main);
            // The handles go on the edited scene's picture only.
            let (marked, other) = if studio_mode {
                (Picture::Scene, Picture::Program)
            } else {
                (Picture::Program, Picture::Scene)
            };
            preview::set_marks(&app.main, marked, app.studio.marks());
            preview::set_marks(&app.main, other, &[]);
            preview::place(&app.main);
        }
    }

    /// The live state on the Dock tile while no window shows it, and a problem added
    /// to it (ADR-0056 decisions 7 and 8). Changes only what differs.
    fn sync_background(app: &mut App) {
        let state = background::LiveState {
            streaming: app.studio.streaming_for().is_some(),
            recording: app.studio.recording_for().is_some(),
            problem: app.hidden && app.error.is_some(),
        };
        if state == app.bg_state {
            return;
        }
        let new_problem = state.problem && !app.bg_state.problem;
        app.bg_state = state;
        #[cfg(target_os = "macos")]
        {
            let badge = background::dock_badge(state).and_then(|t| std::ffi::CString::new(t).ok());
            rbs_app::native::set_badge(badge.as_deref());
            if new_problem {
                rbs_app::native::request_attention();
            }
        }
        #[cfg(not(target_os = "macos"))]
        let _ = new_problem;
        #[cfg(windows)]
        Self::sync_tray_text(app);
    }

    /// Makes or drops the tray icon and the second-launch event as the setting asks
    /// (ADR-0056 decision 9: nothing exists while Quit RBS is set).
    #[cfg(windows)]
    fn sync_tray(app: &mut App) {
        let want = app.bg.on_close == OnClose::KeepRunning && Self::way_back();
        match (&app.tray, want) {
            (None, true) => {
                let (status, tooltip) = Self::tray_text(app);
                match rbs_app::win::Tray::new(app.bg_state, &status, &tooltip) {
                    Ok(tray) => {
                        let event = rbs_app::win::ShowEvent::create(show_from_system);
                        app.tray = Some((tray, event));
                    }
                    Err(e) => {
                        // No way back: Close quits, and the setting's hint says so.
                        studio_ui::log(&format!("tray icon: {e}; closing the window quits"));
                        WAY_BACK.with(|w| w.set(false));
                    }
                }
            }
            (Some(_), false) => app.tray = None,
            _ => {}
        }
    }

    /// The tray menu's status line and the icon's tooltip, in words (U4).
    #[cfg(windows)]
    fn tray_text(app: &App) -> (String, String) {
        let clock = |d: Duration| {
            let s = d.as_secs();
            format!("{:02}:{:02}:{:02}", s / 3600, s / 60 % 60, s % 60)
        };
        let mut status = match (app.studio.streaming_for(), app.studio.recording_for()) {
            (Some((d, host, _)), _) => format!("Live on {host}, {}", clock(d)),
            (None, Some((d, _))) => format!("Recording, {}", clock(d)),
            (None, None) => "Not live".to_owned(),
        };
        if app.bg_state.problem {
            status.push_str(" - a problem needs your attention");
        }
        let tooltip = format!("RBS: {status}");
        (status, tooltip)
    }

    #[cfg(windows)]
    fn sync_tray_text(app: &mut App) {
        let (status, tooltip) = Self::tray_text(app);
        let state = app.bg_state;
        if let Some((tray, _)) = &mut app.tray {
            tray.set_state(state, &status, &tooltip);
        }
    }

    /// Whether a hidden main window can be brought back on this platform now
    /// (ADR-0056 decision 6); without it, Close quits.
    fn way_back() -> bool {
        WAY_BACK.with(Cell::get)
    }

    /// A Close or a Quit (ADR-0056 decision 3). Returns what the close handler answers
    /// the toolkit.
    fn request(&self, request: Request) -> slint::CloseRequestResponse {
        let Ok(mut app) = self.app.try_borrow_mut() else {
            // Borrowed by a callback in progress: quit as before ADR-0056.
            let _ = slint::quit_event_loop();
            return slint::CloseRequestResponse::HideWindow;
        };
        let live = app.studio.st_state != studio_ui::st_state::OFF;
        match background::on_request(&app.bg, request, live, Self::way_back()) {
            Action::Hide { notice: true } => {
                // Said once, in the frame, before the windows go (OK hides them).
                let kind = if cfg!(target_os = "macos") { 1 } else { 2 };
                app.main.global::<Shell>().set_background_notice(kind);
                slint::CloseRequestResponse::KeepWindowShown
            }
            Action::Hide { notice: false } => {
                self.hide_all(&mut app);
                slint::CloseRequestResponse::KeepWindowShown
            }
            Action::AskEndStream => {
                // Ending a stream cannot be undone: the frame asks first (U4), in a
                // window the user can see.
                if app.hidden {
                    self.show_all(&mut app);
                }
                app.main.window().set_minimized(false);
                app.main.global::<Shell>().set_quit_confirm(true);
                slint::CloseRequestResponse::KeepWindowShown
            }
            Action::Quit => {
                app.exiting = true;
                if app.save_due {
                    app.persist_now();
                }
                let _ = app.main.hide();
                drop(app);
                let _ = slint::quit_event_loop();
                slint::CloseRequestResponse::HideWindow
            }
        }
    }

    /// Hides every RBS window and keeps running (ADR-0056 decisions 3 and 5): Settings
    /// closes as by its own close button, floating windows hide without a layout
    /// change, the preview unsubscribes and the meters stop.
    fn hide_all(&self, app: &mut App) {
        if let Some(w) = app.settings.take() {
            let _ = w.hide();
            app.studio.settings_closed();
        }
        app.main.global::<Shell>().set_background_notice(0);
        for f in &app.floats {
            let _ = f.window.hide();
        }
        let _ = app.main.hide();
        #[cfg(any(target_os = "macos", windows))]
        {
            preview::close();
            app.studio.preview_ready = false;
            app.studio.scene_preview_ready = false;
        }
        self.meter_timer.stop();
        app.hidden = true;
        #[cfg(target_os = "macos")]
        rbs_app::native::set_hidden(true);
    }

    /// Shows the windows hidden by [`Self::hide_all`] again and connects the preview.
    fn show_all(&self, app: &mut App) {
        if !app.hidden {
            let _ = app.main.show();
            #[cfg(windows)]
            title_bar::attach_after_show(&app.main);
            return;
        }
        app.hidden = false;
        #[cfg(target_os = "macos")]
        rbs_app::native::set_hidden(false);
        let _ = app.main.show();
        #[cfg(windows)]
        title_bar::attach_after_show(&app.main);
        for f in &app.floats {
            let _ = f.window.show();
        }
        if let Some(endpoint) = app.preview_endpoint.clone() {
            self.connect_preview(endpoint);
        }
        if let Some(endpoint) = app.scene_preview_endpoint.clone() {
            self.connect_scene_preview(endpoint);
        }
        // The views catch up on the next turn of the event loop.
        self.update(|_| {});
    }

    /// The General section's setting (ADR-0056 decision 1).
    fn push_general(app: &App) {
        let platform = if cfg!(target_os = "macos") {
            0
        } else if cfg!(windows) {
            1
        } else {
            2
        };
        let on_close = i32::from(app.bg.on_close == OnClose::KeepRunning);
        let push = |g: Studio<'_>| {
            g.set_platform(platform);
            g.set_on_close(on_close);
            g.set_way_back(Self::way_back());
        };
        push(app.main.global::<Studio>());
        if let Some(w) = &app.settings {
            push(w.global::<Studio>());
        }
    }

    fn sync(&self) {
        let Ok(mut app) = self.app.try_borrow_mut() else {
            return;
        };
        let queued: Vec<Op> = std::mem::take(&mut *self.queue.borrow_mut());
        for op in queued {
            entry::guard(|| op(&mut app));
        }
        if app.exiting {
            return;
        }
        if std::mem::take(&mut app.reload_themes) {
            appearance_page::reload(self, &mut app);
        }
        if std::mem::take(&mut app.open_app_menu) {
            // Out of the background first (ADR-0056), so the window is current.
            self.show_all(&mut app);
            let s = app.main.global::<Shell>();
            s.set_app_menu_asked(s.get_app_menu_asked().wrapping_add(1));
        }
        if let Some(section) = app.open_settings.take() {
            // Without a section: where the open window is, else General (listed first).
            let section = section
                .or_else(|| app.settings.as_ref().map(|w| w.get_section()))
                .unwrap_or(SECTION_GENERAL);
            self.open_settings(section);
        }
        vcam_page::sync_host(&mut app);
        self.sync_live(&mut app);
        #[cfg(windows)]
        Self::sync_tray(&mut app);
        Self::sync_background(&mut app);
        // Nothing to draw while hidden; the windows catch up when they show (U5).
        if app.hidden {
            self.meter_timer.stop();
            return;
        }
        Self::push_general(&app);
        vcam_page::push(&app);

        // Main window.
        let (stacks, handles, rail) = view::window_view(
            0,
            &app.session.workspace().windows[0],
            app.area(0),
            app.maximized.as_ref(),
            app.studio.studio_mode,
        );
        app.main_models.update(stacks, handles);
        let rail_shown = rail.shown;
        if app.main.get_rail() != rail {
            app.main.set_rail(rail);
        }
        if rail_shown {
            let keys = self.keys.borrow().label_for("canvas.transition");
            let shell = app.main.global::<Shell>();
            if shell.get_transition_keys() != keys.as_str() {
                shell.set_transition_keys(keys.into());
            }
        }

        self.sync_floats(&mut app);

        // Shared state, pushed into every window's copy of the global.
        set_rows(
            &app.panels_model,
            view::panel_entries(app.session.workspace()),
        );
        let entries = view::workspace_entries(&app.workspaces, &app.session.workspace().name);
        set_rows(&app.workspaces_model, entries);
        // The question goes once the stream ends some other way.
        if !matches!(
            app.studio.st_state,
            studio_ui::st_state::LIVE | studio_ui::st_state::STARTING
        ) {
            app.confirm_end = false;
        }
        let edges = view::edge_tabs(&app.session.workspace().windows[0]);
        let edge_ids = edges
            .iter()
            .flatten()
            .map(|t| t.id.as_str())
            .collect::<Vec<_>>()
            .join("\n");
        let edge_models = edges.map(|v| ModelRc::new(VecModel::from(v)));
        // Only macOS shows a menu bar (ADR-0069); elsewhere its values go unused (P13).
        if cfg!(target_os = "macos") {
            let values = menu_bar::values(&app.shown());
            app.menus.update(values);
        }
        let (row, toolbar_visible) = menu_bar::toolbar(&app.shown());
        let data = |items: Vec<menu_bar::ToolItem>| -> Vec<ToolbarData> {
            items
                .into_iter()
                .map(|t| ToolbarData {
                    id: t.id.into(),
                    title: t.title.into(),
                    kind: t.kind as i32,
                    enabled: t.enabled,
                    checked: t.checked,
                    live: t.live,
                    icon: t.icon.into(),
                    icon_only: t.icon_only,
                })
                .collect()
        };
        set_rows(&app.toolbar_model, data(row.lead));
        set_rows(&app.toolbar_end_model, data(row.end));
        set_rows(&app.toolbar_fixed_model, data(row.fixed));
        let ws = app.session.workspace();
        let live = app.session.live();
        let (toast_kind, toast_subject) = match &app.toast {
            Some(Toast::ClosedWhileLive(id)) => (1, view::title(id)),
            Some(Toast::SwitchedAutomatically { previous }) => (2, previous.clone()),
            None => (0, String::new()),
        };
        let (error_kind, error_detail) = match &app.error {
            Some(UiError::Locked) => (1, String::new()),
            Some(UiError::Other(e)) => (2, e.clone()),
            Some(UiError::Notice(e)) => (3, e.clone()),
            None => (0, String::new()),
        };
        let panels = ModelRc::from(app.panels_model.clone());
        let toolbar = ModelRc::from(app.toolbar_model.clone());
        let toolbar_end = ModelRc::from(app.toolbar_end_model.clone());
        let toolbar_fixed = ModelRc::from(app.toolbar_fixed_model.clone());
        let workspaces = ModelRc::from(app.workspaces_model.clone());
        let push = |g: Shell<'_>| {
            g.set_live_state(view::live_code(live));
            g.set_live_duration(live.duration_text().into());
            g.set_live_outputs(live.outputs_text().into());
            g.set_live_camera(live.camera);
            g.set_panels(panels.clone());
            g.set_workspaces(workspaces.clone());
            g.set_workspace_name(ws.name.as_str().into());
            g.set_workspace_built_in(builtin::is_built_in(&ws.name));
            g.set_locked(ws.locked);
            g.set_can_undo(app.session.can_undo());
            g.set_can_redo(app.session.can_redo());
            g.set_toast_kind(toast_kind);
            g.set_toast_subject(toast_subject.as_str().into());
            g.set_error_kind(error_kind);
            g.set_error_detail(error_detail.as_str().into());
            g.set_end_stream_confirm(app.confirm_end);
            g.set_toolbar(toolbar.clone());
            g.set_toolbar_visible(toolbar_visible);
            g.set_toolbar_end(toolbar_end.clone());
            g.set_toolbar_fixed(toolbar_fixed.clone());
            g.set_gap(rbs_ui::layout::HANDLE_THICKNESS);
            g.set_maximized(app.maximized.as_ref().map_or("", |p| p.as_str()).into());
            g.set_edge_ids(edge_ids.as_str().into());
            g.set_left_tabs(edge_models[0].clone());
            g.set_right_tabs(edge_models[1].clone());
            g.set_bottom_tabs(edge_models[2].clone());
        };
        push(app.main.global::<Shell>());
        app.menus.push(&app.main.global::<Menus>());
        for f in &app.floats {
            push(f.window.global::<Shell>());
            app.menus.push(&f.window.global::<Menus>());
        }

        if app.toast.is_some() {
            if self.toast_shown.get() != app.toast_serial || !self.toast_timer.running() {
                self.toast_shown.set(app.toast_serial);
                let ctx = self.clone();
                entry::start(
                    &self.toast_timer,
                    slint::TimerMode::SingleShot,
                    TOAST_TIME,
                    move || {
                        ctx.update(|app| app.toast = None);
                    },
                );
            }
        } else {
            self.toast_timer.stop();
        }
        self.sync_studio(&mut app);
        if app.save_due {
            let ctx = self.clone();
            entry::start(
                &self.save_timer,
                slint::TimerMode::SingleShot,
                SAVE_DELAY,
                move || {
                    ctx.update(App::persist_now);
                },
            );
        }
    }

    /// One OS window per floating workspace window. An OS window keeps showing
    /// the workspace window that shares a panel with it, so its position, size
    /// and focus survive docks, moves and undo; leftover OS windows are reused
    /// in order before a new one is created.
    fn sync_floats(&self, app: &mut App) {
        let ws = app.session.workspace();
        let wanted: Vec<(usize, Vec<PanelId>)> = ws
            .windows
            .iter()
            .enumerate()
            .filter(|(_, w)| matches!(w.content, WindowContent::Floating(_)))
            .filter_map(|(i, w)| {
                w.layout()
                    .map(|l| (i, l.panels().into_iter().cloned().collect()))
            })
            .collect();
        let mut old: Vec<Option<FloatSlot>> = std::mem::take(&mut app.floats)
            .into_iter()
            .map(Some)
            .collect();
        let mut chosen: Vec<Option<FloatSlot>> = wanted
            .iter()
            .map(|(_, panels)| {
                old.iter_mut()
                    .find(|s| {
                        s.as_ref()
                            .is_some_and(|s| s.panels.iter().any(|p| panels.contains(p)))
                    })
                    .and_then(Option::take)
            })
            .collect();
        let mut leftover = old.into_iter().flatten();
        for c in chosen.iter_mut().filter(|c| c.is_none()) {
            *c = leftover.next();
        }
        for s in leftover {
            let _ = s.window.hide();
        }

        // Sizes follow their OS window to its new workspace window index.
        let old_areas = std::mem::take(&mut app.areas);
        let area_of = |i: usize| old_areas.iter().find(|(w, _)| *w == i).map(|(_, r)| *r);
        app.areas.extend(area_of(0).map(|r| (0, r)));
        let mut slots = Vec::with_capacity(wanted.len());
        for ((w, panels), slot) in wanted.into_iter().zip(chosen) {
            let Some(slot) = slot.or_else(|| self.new_float()) else {
                continue;
            };
            if let Some(r) = slot.index.and_then(area_of) {
                app.areas.push((w, r));
            }
            let Some(layout) = app.session.workspace().windows[w].layout() else {
                continue;
            };
            let (stacks, handles, _) = view::window_view(
                w,
                &app.session.workspace().windows[w],
                app.area(w),
                app.maximized.as_ref(),
                app.studio.studio_mode,
            );
            slot.models.update(stacks, handles);
            slot.window.set_window(w as i32);
            slot.window.set_panel_names(view::panel_names(layout));
            slots.push(FloatSlot {
                panels,
                index: Some(w),
                ..slot
            });
        }
        app.floats = slots;
    }

    fn new_float(&self) -> Option<FloatSlot> {
        let fw = FloatWindow::new().ok()?;
        install(&fw.global::<Shell>(), self);
        install_menus(&fw.global::<Menus>(), self);
        install_context_menus(&fw.global::<ContextMenus>(), self);
        shortcuts_page::install_press(&fw.global::<Shortcuts>(), self);
        install_studio(&fw.global::<Studio>(), self);
        install_sections(&fw.global::<Sections>(), self);
        look::apply(
            &fw.global::<Theme>(),
            &fw.global::<Tokens>(),
            self.look.borrow().as_ref(),
        );
        let models = DockModels::new();
        fw.set_stacks(ModelRc::from(models.stacks.clone()));
        fw.set_handles(ModelRc::from(models.handles.clone()));
        let ctx = self.clone();
        let weak = fw.as_weak();
        entry::on_close_requested(fw.window(), move || {
            if let Some(fw) = weak.upgrade() {
                let w = fw.get_window() as usize;
                ctx.update(move |app| {
                    if !app.exiting {
                        app.command(LayoutCommand::CloseWindow { window: w }, Origin::Command);
                    }
                });
            }
            slint::CloseRequestResponse::HideWindow
        });
        let _ = fw.show();
        Some(FloatSlot {
            window: fw,
            panels: Vec::new(),
            index: None,
            models,
        })
    }
}

fn edge(code: i32) -> Edge {
    match code {
        0 => Edge::Left,
        1 => Edge::Right,
        2 => Edge::Top,
        _ => Edge::Bottom,
    }
}

/// A drag payload holding `text` (a panel id or a source id).
fn text_data(text: slint::SharedString) -> slint::DataTransfer {
    let mut d = slint::DataTransfer::default();
    d.set_plain_text(text);
    d
}

fn panel(id: &str) -> Option<PanelId> {
    PanelId::parse(id).ok()
}

/// Connect one window's `Shell` callbacks to the shared state.
fn install(g: &Shell<'_>, ctx: &Ctx) {
    macro_rules! on {
        ($name:ident, |$app:ident $(, $arg:ident : $ty:ty)*| $body:block) => {{
            let ctx = ctx.clone();
            g.$name(move |$($arg: $ty),*| ctx.update(move |$app: &mut App| $body));
        }};
    }
    {
        let ctx = ctx.clone();
        g.on_relayout(move |window: i32, x: f32, y: f32, w: f32, h: f32| {
            ctx.update(move |app: &mut App| {
                if window == 0 {
                    app.main_origin = (x, y);
                }
                app.set_area(window as usize, Rect::sized(w, h));
            });
            // Not only on the next event loop turn: while the user drags a window's
            // edge on Windows, the system's resize loop runs no timers, so the panels
            // would keep their old size until the mouse is released.
            ctx.relayout_now(window as usize);
        });
    }
    g.on_panel_data(|id| entry::guard_or(slint::DataTransfer::default, || text_data(id)));
    on!(on_drag_over, |app,
                       window: i32,
                       data: slint::DataTransfer,
                       x: f32,
                       y: f32| {
        let p = data.plain_text().ok().and_then(|t| panel(&t));
        app.drag_over(window as usize, p, x, y);
    });
    on!(on_drag_drop, |app,
                       window: i32,
                       data: slint::DataTransfer,
                       x: f32,
                       y: f32| {
        let p = data.plain_text().ok().and_then(|t| panel(&t));
        app.drag_drop(window as usize, p, x, y);
    });
    on!(on_drag_leave, |app| {
        app.show_drop_guide(None);
    });
    on!(on_collapse, |app,
                      id: slint::SharedString,
                      collapsed: bool| {
        if let Some(panel) = panel(&id) {
            // Collapse and expand stay allowed while locked (ADR-0049).
            app.command(
                LayoutCommand::SetCollapsed { panel, collapsed },
                Origin::Pointer,
            );
        }
    });
    on!(on_auto_hide, |app, id: slint::SharedString| {
        if let Some(panel) = panel(&id) {
            let content = app.area(0);
            app.command(LayoutCommand::AutoHide { panel, content }, Origin::Pointer);
        }
    });
    on!(on_pin, |app, id: slint::SharedString| {
        if let Some(panel) = panel(&id) {
            app.command(LayoutCommand::Pin(panel), Origin::Pointer);
        }
    });
    on!(on_activate_tab, |app, window: i32, stack: i32, tab: i32| {
        let c = LayoutCommand::ActivateTab {
            window: window as usize,
            stack: stack as usize,
            tab: tab as usize,
        };
        app.command(c, Origin::Pointer);
    });
    on!(on_close_panel, |app, id: slint::SharedString| {
        if let Some(id) = panel(&id) {
            app.command(LayoutCommand::ClosePanel(id), Origin::Pointer);
        }
    });
    on!(on_toggle_panel, |app, id: slint::SharedString| {
        if let Some(id) = panel(&id) {
            let c = if app.session.workspace().is_open(&id) {
                LayoutCommand::ClosePanel(id)
            } else {
                LayoutCommand::OpenPanel(id)
            };
            app.command(c, Origin::Command);
        }
    });
    on!(on_move_edge, |app,
                       id: slint::SharedString,
                       window: i32,
                       e: i32| {
        if let Some(id) = panel(&id) {
            let c = LayoutCommand::MoveToEdge {
                panel: id,
                window: window as usize,
                edge: edge(e),
            };
            app.command(c, Origin::Command);
        }
    });
    on!(on_move_next_stack, |app, id: slint::SharedString| {
        if let Some(id) = panel(&id)
            && let Some((w, s, _)) = app.session.workspace().find(&id)
        {
            let count = app.session.workspace().windows[w].stack_count();
            if count > 1 {
                let c = LayoutCommand::MoveToStack {
                    panel: id,
                    window: w,
                    stack: (s + 1) % count,
                };
                app.command(c, Origin::Command);
            }
        }
    });
    on!(on_float_panel, |app, id: slint::SharedString| {
        if let Some(id) = panel(&id) {
            app.command(LayoutCommand::Float(id), Origin::Command);
        }
    });
    on!(on_dock, |app, window: i32| {
        app.command(
            LayoutCommand::Dock {
                window: window as usize,
            },
            Origin::Command,
        );
    });
    on!(on_drag, |app, window: i32, handle: i32, position: f32| {
        app.drag(window as usize, handle as usize, position);
    });
    on!(on_drag_end, |app| {
        app.end_drag();
    });
    on!(on_nudge, |app, window: i32, handle: i32, delta: f32| {
        let window = window as usize;
        let c = LayoutCommand::Resize {
            window,
            area: app.area(window),
            handle: handle as usize,
            delta,
            group: None,
            studio_mode: app.studio.studio_mode,
        };
        app.command(c, Origin::Command);
    });
    on!(on_switch_workspace, |app, name: slint::SharedString| {
        app.switch_workspace(&name);
    });
    on!(on_save_workspace, |app| {
        app.persist_now();
        app.refresh_list();
    });
    on!(on_save_workspace_as, |app, name: slint::SharedString| {
        let current = app.session.workspace().clone();
        match app.store.save_as(&current, name.trim()) {
            Ok(ws) => {
                app.command(LayoutCommand::Switch(ws), Origin::Command);
                app.refresh_list();
            }
            Err(e) => app.error = Some(UiError::Other(e.to_string())),
        }
    });
    on!(on_restore_workspace, |app| {
        let name = app.session.workspace().name.clone();
        match app.store.restore_default(&name) {
            Ok(ws) => {
                app.command(LayoutCommand::Switch(ws), Origin::Command);
                app.refresh_list();
            }
            Err(e) => app.error = Some(UiError::Other(e.to_string())),
        }
    });
    on!(on_set_locked, |app, locked: bool| {
        app.command(LayoutCommand::SetLocked(locked), Origin::Command);
    });
    on!(on_undo, |app| {
        app.undo();
    });
    on!(on_redo, |app| {
        app.redo();
    });
    on!(on_toast_undo, |app| {
        if app.toast.is_some() {
            app.undo();
        }
    });
    on!(on_toast_dismiss, |app| {
        app.toast = None;
    });
    on!(on_dismiss_error, |app| {
        app.error = None;
    });
    on!(on_end_stream_answer, |app, end: bool| {
        app.confirm_end = false;
        if end {
            app.studio.end_stream();
        }
    });
}

