/// Connect the main window's RBS menu to the shared state. Rows are made when the
/// menu asks, so it shows the state of the moment and costs nothing while closed.
fn install_app_menu(g: &AppMenus<'_>, ctx: &Ctx) {
    let c = ctx.clone();
    let main = ctx.app.borrow().main.as_weak();
    g.on_prepare(move || {
        entry::guard(|| {
            let Some(main) = main.upgrade() else { return };
            let g = main.global::<AppMenus>();
            let (Ok(app), Ok(keys)) = (c.app.try_borrow(), c.keys.try_borrow()) else {
                return;
            };
            let shown = app.shown();
            let cats: Vec<slint::SharedString> = app_menu::categories(&shown)
                .into_iter()
                .map(Into::into)
                .collect();
            g.set_categories(ModelRc::new(VecModel::from(cats)));
            let chips: Vec<AppMenuChip> = app_menu::profiles(&shown)
                .into_iter()
                .map(|(title, id, current)| AppMenuChip {
                    title: title.into(),
                    id: id.into(),
                    current,
                })
                .collect();
            g.set_profiles(ModelRc::new(VecModel::from(chips)));
            g.set_search_shortcut(keys.label("ui.app_menu.open").unwrap_or_default().into());
            g.set_settings_shortcut(keys.label("ui.settings.open").unwrap_or_default().into());
        })
    });
    let c = ctx.clone();
    g.on_rows(move |category, picker, query| {
        let rows = match (c.app.try_borrow(), c.keys.try_borrow()) {
            (Ok(app), Ok(keys)) => entry::guard_or(Vec::new, || {
                app_menu::rows(
                    &app.shown(),
                    usize::try_from(category).unwrap_or(0),
                    &picker,
                    &query,
                    &|id| keys.label(id),
                )
            }),
            _ => Vec::new(),
        };
        let rows: Vec<AppMenuRow> = rows
            .into_iter()
            .map(|r| AppMenuRow {
                kind: r.kind as i32,
                title: r.title.into(),
                icon: r.icon.into(),
                shortcut: r.shortcut.into(),
                value: r.value.into(),
                id: r.id.into(),
                enabled: r.enabled,
                checkable: r.checkable,
                checked: r.checked,
                reason: r.reason.into(),
                up: r.up.and_then(|i| i32::try_from(i).ok()).unwrap_or(-1),
                down: r.down.and_then(|i| i32::try_from(i).ok()).unwrap_or(-1),
            })
            .collect();
        ModelRc::new(VecModel::from(rows))
    });
    let c = ctx.clone();
    g.on_run(move |id| c.update(move |app| app.run_command(&id)));
}

/// Connect one window's context menus to the shared state. The items are made at
/// once, so the menu shows the state of the moment; the selection a right-click makes
/// reaches the views on the next sync.
/// The name prompt of the main window (Save as new): Enter saves, and a refusal stays
/// in the prompt as its error line; Escape or the Cancel button closes it.
fn install_name_prompt(g: &Overlays<'_>, ctx: &Ctx) {
    {
        let ctx = ctx.clone();
        g.on_name_accepted(move |name| {
            let name = name.to_string();
            ctx.update(move |app: &mut App| {
                let done = match app.name_for {
                    Some(Ask::Entry(kind, op)) => app.entry_command(kind, op, &name),
                    _ => app.save_workspace_as(&name),
                };
                let o = app.main.global::<Overlays>();
                match done {
                    Ok(()) => o.set_name_open(false),
                    Err(e) => o.set_name_error(e.into()),
                }
            });
        });
    }
    let ctx = ctx.clone();
    g.on_name_cancelled(move || {
        entry::guard(|| {
            ctx.update(|app: &mut App| {
                app.name_for = None;
                app.main.global::<Overlays>().set_name_open(false);
            });
        });
    });
}

/// The Add vertical output dialog: Add and Remove send the host's commands and close
/// it (a refusal comes back as a notice); Escape or Cancel closes it.
fn install_vertical_prompt(g: &Overlays<'_>, ctx: &Ctx) {
    use rbs_app::studio_host::{Command, VerticalCanvas};
    use rbs_core::media::Size;
    use rbs_scene::AutoLayout;
    {
        let ctx = ctx.clone();
        g.on_vertical_accepted(move || {
            entry::guard(|| {
                ctx.update(|app: &mut App| {
                    let o = app.main.global::<Overlays>();
                    let (w, h) = match o.get_vertical_size() {
                        0 => (1080.0, 1920.0),
                        1 => (720.0, 1280.0),
                        _ => (o.get_vertical_w(), o.get_vertical_h()),
                    };
                    let fits =
                        |v: f32| (64.0..=8192.0).contains(&v) && v.fract() == 0.0 && v % 2.0 == 0.0;
                    if !fits(w) || !fits(h) {
                        o.set_vertical_error(
                            "Width and height must be even numbers from 64 to 8192.".into(),
                        );
                        return;
                    }
                    let layout = match o.get_vertical_layout() {
                        1 => Some(AutoLayout::Fit),
                        2 => Some(AutoLayout::Fill),
                        3 => Some(AutoLayout::Stack),
                        _ => None,
                    };
                    app.studio.send(Command::AddVerticalCanvas(VerticalCanvas {
                        size: Size::new(w as u32, h as u32),
                        follow: o.get_vertical_follow(),
                        layout,
                    }));
                    o.set_vertical_open(false);
                });
            });
        });
    }
    {
        let ctx = ctx.clone();
        g.on_vertical_removed(move || {
            entry::guard(|| {
                ctx.update(|app: &mut App| {
                    app.studio.send(Command::RemoveVerticalCanvas);
                    app.main.global::<Overlays>().set_vertical_open(false);
                });
            });
        });
    }
    let ctx = ctx.clone();
    g.on_vertical_cancelled(move || {
        entry::guard(|| {
            ctx.update(|app: &mut App| {
                app.main.global::<Overlays>().set_vertical_open(false);
            });
        });
    });
}

