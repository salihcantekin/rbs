//! Generates `tokens.slint` from the design token file (rule U6) and compiles the UI.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::time::SystemTime;

use rbs_ui::tokens::{THEMES, Tokens};

/// `color.surface.base` -> `surface-base`; `space.1` -> `space-1`.
fn ident(name: &str, strip: &str) -> String {
    name.strip_prefix(strip).unwrap_or(name).replace('.', "-")
}

/// `color.surface.base` -> `surface_base` (the Rust name Slint gives a field or setter).
fn rust(name: &str, strip: &str) -> String {
    ident(name, strip).replace('-', "_")
}

/// `tokens.slint`: the `Theme` and `Tokens` globals. Every value is an `in-out`
/// property whose default is the built-in token file, so the files compile and preview
/// on their own; the app sets them at run time from the token file in use
/// (`tokens_apply.rs`). Theme colours are one `ThemeColors` entry per theme, in
/// `THEMES` order, and `Theme.active` picks one.
fn generate(t: &Tokens) -> Result<String, std::fmt::Error> {
    let mut s = String::new();
    writeln!(
        s,
        "// Generated by crates/rbs-app/build.rs from crates/rbs-ui/tokens.toml. Do not edit."
    )?;
    writeln!(s, "import {{ Palette }} from \"std-widgets.slint\";")?;
    let names: Vec<&String> = t.themes[0].1.keys().collect();
    writeln!(s, "// The colours of one theme.")?;
    writeln!(s, "export struct ThemeColors {{")?;
    for name in &names {
        writeln!(s, "    {}: color,", ident(name, "color."))?;
    }
    writeln!(s, "}}")?;
    writeln!(s, "export global Theme {{")?;
    writeln!(
        s,
        "    // -1 follows the OS; otherwise an index into: {}.",
        THEMES.join(", ")
    )?;
    writeln!(s, "    in-out property <int> choice: -1;")?;
    writeln!(
        s,
        "    // One entry per theme, in the order above; set by the app."
    )?;
    writeln!(s, "    in-out property <[ThemeColors]> themes: [")?;
    for (_, colors) in &t.themes {
        write!(s, "        {{")?;
        for (i, name) in names.iter().enumerate() {
            let sep = if i == 0 { "" } else { ", " };
            write!(s, "{sep}{}: {}", ident(name, "color."), colors[*name])?;
        }
        writeln!(s, "}},")?;
    }
    writeln!(s, "    ];")?;
    writeln!(
        s,
        "    out property <int> active: choice >= 0 ? choice : (Palette.color-scheme == ColorScheme.light ? 1 : 0);"
    )?;
    writeln!(s, "    out property <bool> high-contrast: active == 2;")?;
    for (name, c) in &t.fixed {
        writeln!(
            s,
            "    out property <color> {}: {c};",
            ident(name, "color.")
        )?;
    }
    for name in &names {
        let id = ident(name, "color.");
        writeln!(s, "    out property <color> {id}: themes[active].{id};")?;
    }
    writeln!(s, "}}")?;
    writeln!(s, "export global Tokens {{")?;
    for (name, v) in &t.length {
        writeln!(
            s,
            "    in-out property <length> {}: {v}px;",
            ident(name, "")
        )?;
    }
    for (name, v) in &t.duration {
        writeln!(
            s,
            "    in-out property <duration> {}: {v}ms;",
            ident(name, "")
        )?;
    }
    for (name, ty) in &t.type_styles {
        let id = ident(name, "");
        writeln!(s, "    in-out property <length> {id}-size: {}px;", ty.size)?;
        writeln!(s, "    in-out property <length> {id}-line: {}px;", ty.line)?;
        writeln!(s, "    in-out property <int> {id}-weight: {};", ty.weight)?;
    }
    writeln!(s, "}}")?;
    Ok(s)
}

/// `tokens_apply.rs`: one function that copies a parsed token file into a window's
/// `Theme` and `Tokens` globals. Included into the app next to the Slint code, so a
/// token added to the file needs no hand-written setter.
fn generate_apply(t: &Tokens) -> Result<String, std::fmt::Error> {
    let mut s = String::new();
    writeln!(
        s,
        "// Generated by crates/rbs-app/build.rs from crates/rbs-ui/tokens.toml. Do not edit."
    )?;
    writeln!(
        s,
        "/// Copies `file` into a window's `Theme` and `Tokens` globals. Fails, changing\n\
         /// nothing, if `file` lacks a token the app uses (`rbs_ui::tokens` refuses such\n\
         /// files, so this happens only for a token file of another build)."
    )?;
    writeln!(
        s,
        "pub fn apply_tokens(theme: &Theme<'_>, tokens: &Tokens<'_>, file: &rbs_ui::tokens::Tokens) -> Result<(), String> {{"
    )?;
    writeln!(
        s,
        "    let color = |c: rbs_ui::tokens::Color| slint::Color::from_argb_u8(c.a, c.r, c.g, c.b);"
    )?;
    writeln!(s, "    let mut themes = Vec::new();")?;
    writeln!(s, "    for name in rbs_ui::tokens::THEMES {{")?;
    writeln!(
        s,
        "        let colors = &file.themes.iter().find(|(n, _)| n == name).ok_or_else(|| format!(\"no theme {{name}}\"))?.1;"
    )?;
    writeln!(
        s,
        "        let get = |token: &str| colors.get(token).copied().map(color).ok_or_else(|| format!(\"no {{token}} in theme {{name}}\"));"
    )?;
    writeln!(s, "        themes.push(ThemeColors {{")?;
    for name in t.themes[0].1.keys() {
        writeln!(s, "            {}: get(\"{name}\")?,", rust(name, "color."))?;
    }
    writeln!(s, "        }});")?;
    writeln!(s, "    }}")?;
    writeln!(
        s,
        "    let length = |n: &str| file.length.get(n).copied().ok_or_else(|| format!(\"no {{n}}\"));"
    )?;
    writeln!(
        s,
        "    let duration = |n: &str| file.duration.get(n).map(|v| i64::from(*v)).ok_or_else(|| format!(\"no {{n}}\"));"
    )?;
    writeln!(
        s,
        "    let style = |n: &str| file.type_styles.get(n).copied().ok_or_else(|| format!(\"no {{n}}\"));"
    )?;
    // Read everything first, so a missing token changes nothing.
    for name in t.length.keys() {
        writeln!(s, "    let {} = length(\"{name}\")?;", rust(name, ""))?;
    }
    for name in t.duration.keys() {
        writeln!(s, "    let {} = duration(\"{name}\")?;", rust(name, ""))?;
    }
    for name in t.type_styles.keys() {
        writeln!(s, "    let {} = style(\"{name}\")?;", rust(name, ""))?;
    }
    writeln!(
        s,
        "    theme.set_themes(slint::ModelRc::new(slint::VecModel::from(themes)));"
    )?;
    for name in t.length.keys() {
        let r = rust(name, "");
        writeln!(s, "    tokens.set_{r}({r});")?;
    }
    for name in t.duration.keys() {
        let r = rust(name, "");
        writeln!(s, "    tokens.set_{r}({r});")?;
    }
    for name in t.type_styles.keys() {
        let r = rust(name, "");
        writeln!(s, "    tokens.set_{r}_size(f32::from({r}.size));")?;
        writeln!(s, "    tokens.set_{r}_line(f32::from({r}.line));")?;
        writeln!(s, "    tokens.set_{r}_weight(i32::from({r}.weight));")?;
    }
    writeln!(s, "    Ok(())")?;
    writeln!(s, "}}")?;
    Ok(s)
}

/// Writes a generated file into `OUT_DIR` and gives it the token file's modification
/// time. slint-build asks cargo to rerun this script when a file the UI includes changes,
/// and `tokens.slint` is one of them: a file written during the run is newer than the run
/// itself, so without the older time every cargo command saw rbs-app as changed and
/// rebuilt it (about a minute per CI step). Backdating is safe: whenever the content can
/// change, `tokens.toml` changed, the script runs again and rbs-app is rebuilt anyway.
fn write_generated(path: &Path, text: &str, modified: SystemTime) {
    if let Err(e) = std::fs::write(path, text) {
        panic!("writing {}: {e}", path.display());
    }
    let file = match std::fs::File::options().write(true).open(path) {
        Ok(f) => f,
        Err(e) => panic!("opening {}: {e}", path.display()),
    };
    if let Err(e) = file.set_modified(modified) {
        panic!("setting the modification time of {}: {e}", path.display());
    }
}

fn main() {
    println!("cargo:rerun-if-changed=../rbs-ui/tokens.toml");
    // The token file's own time (older than this run); the epoch if it cannot be read.
    let modified = std::fs::metadata("../rbs-ui/tokens.toml")
        .and_then(|m| m.modified())
        .unwrap_or(SystemTime::UNIX_EPOCH);
    let tokens = match Tokens::built_in() {
        Ok(t) => t,
        Err(e) => panic!("{e}"),
    };
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default());
    let text = match generate(&tokens) {
        Ok(t) => t,
        Err(e) => panic!("generating tokens.slint: {e}"),
    };
    write_generated(&out.join("tokens.slint"), &text, modified);
    let apply = match generate_apply(&tokens) {
        Ok(t) => t,
        Err(e) => panic!("generating tokens_apply.rs: {e}"),
    };
    write_generated(&out.join("tokens_apply.rs"), &apply, modified);
    let config = slint_build::CompilerConfiguration::new().with_include_paths(vec![out]);
    if let Err(e) = slint_build::compile_with_config("ui/app.slint", config) {
        panic!("{e}");
    }
}
