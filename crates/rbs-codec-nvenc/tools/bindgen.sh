#!/bin/sh
# Regenerates src/sys/nvenc_api.rs from FFmpeg's nv-codec-headers (MIT licence, a
# redistribution of the NVIDIA Video Codec SDK header). Needs bindgen-cli 0.73 and
# libclang. Run from the repository root. Bumping the SDK version also means updating
# the version constants in src/sys/mod.rs and the minimum driver in the crate docs.
set -eu
TAG=n12.1.14.0
OUT=crates/rbs-codec-nvenc/src/sys/nvenc_api.rs
TMP=$(mktemp -d)
curl -sSfL -o "$TMP/nvEncodeAPI.h" \
  "https://raw.githubusercontent.com/FFmpeg/nv-codec-headers/$TAG/include/ffnvcodec/nvEncodeAPI.h"
bindgen "$TMP/nvEncodeAPI.h" \
  --allowlist-type 'NV_ENCODE_API_FUNCTION_LIST|NV_ENC_.*|NVENCSTATUS|GUID' \
  --no-doc-comments --use-core --default-enum-style consts --no-prepend-enum-name \
  --rust-target 1.87 --with-derive-default --no-debug '.*' \
  --raw-line "// Generated by bindgen 0.73.2 from FFmpeg nv-codec-headers $TAG (include/ffnvcodec/nvEncodeAPI.h," \
  --raw-line '// NVIDIA Video Codec SDK 12.1, MIT licence; see the module docs). Do not edit; regenerate with' \
  --raw-line '// crates/rbs-codec-nvenc/tools/bindgen.sh.' \
  -o "$OUT" -- -I"$TMP"
rm -rf "$TMP"
