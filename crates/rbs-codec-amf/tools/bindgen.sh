#!/bin/sh
# Regenerates src/sys/amf_api.rs from AMD's AMF SDK headers (MIT licence), in C
# mode (vtable structs). Needs bindgen-cli 0.73 and libclang. Run from the
# repository root. `wchar_t` is left to src/sys/mod.rs (16 bits on Windows, 32 on
# Linux). The runtime version check uses AMF_FULL_VERSION, which follows the
# generated version constants.
set -eu
TAG=v1.4.33
OUT=${OUT:-crates/rbs-codec-amf/src/sys/amf_api.rs}
TMP=$(mktemp -d)
BASE="https://raw.githubusercontent.com/GPUOpen-LibrariesAndSDKs/AMF/$TAG/amf/public/include"
for h in core/AudioBuffer.h core/Buffer.h core/Compute.h core/ComputeFactory.h \
  core/Context.h core/Data.h core/Debug.h core/Factory.h core/Interface.h core/Plane.h \
  core/Platform.h core/PropertyStorage.h core/PropertyStorageEx.h core/Result.h \
  core/Surface.h core/Trace.h core/Variant.h core/Version.h components/ColorSpace.h \
  components/Component.h components/ComponentCaps.h components/PreAnalysis.h \
  components/VideoEncoderHEVC.h components/VideoEncoderVCE.h; do
  mkdir -p "$TMP/$(dirname "$h")"
  curl -sSfL -o "$TMP/$h" "$BASE/$h"
done
cat > "$TMP/wrapper.h" <<'H'
#include "core/Factory.h"
#include "core/Buffer.h"
#include "core/Surface.h"
#include "components/ComponentCaps.h"
#include "components/VideoEncoderVCE.h"
#include "components/VideoEncoderHEVC.h"
H
bindgen "$TMP/wrapper.h" \
  --allowlist-type 'AMF.*|amf_.*' --allowlist-var 'AMF_.*' --blocklist-function '.*' \
  --blocklist-type 'wchar_t' \
  --no-doc-comments --use-core --default-enum-style consts --no-prepend-enum-name \
  --rust-target 1.87 --with-derive-default --no-debug '.*' \
  --raw-line "// Generated by bindgen 0.73.2 from AMD AMF SDK $TAG (amf/public/include, C mode," \
  --raw-line '// MIT licence, "Copyright (c) Advanced Micro Devices, Inc."). Do not edit; regenerate' \
  --raw-line '// with crates/rbs-codec-amf/tools/bindgen.sh.' \
  --raw-line 'use super::wchar_t;' \
  -o "$OUT" -- -I"$TMP"
rm -rf "$TMP"
