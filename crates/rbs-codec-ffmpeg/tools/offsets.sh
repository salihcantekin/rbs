#!/bin/sh
# Prints the struct field offsets the adapter uses (src/linux.rs, LAYOUTS) for each
# FFmpeg release given, from its public headers. Needs a C compiler and network
# access to ffmpeg.org. Usage: tools/offsets.sh 6.1 7.0 8.0
set -eu
here=$(cd "$(dirname "$0")" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
for v in "$@"; do
    curl -sSL -o "$work/ffmpeg-$v.tar.xz" "https://ffmpeg.org/releases/ffmpeg-$v.tar.xz"
    mkdir -p "$work/$v"
    tar xJf "$work/ffmpeg-$v.tar.xz" -C "$work/$v" --strip-components=1 \
        --wildcards '*/libavutil/*.h' '*/libavcodec/*.h'
    # avconfig.h is generated by FFmpeg's configure; these are its values on
    # little-endian x86_64 and aarch64.
    printf '#define AV_HAVE_BIGENDIAN 0\n#define AV_HAVE_FAST_UNALIGNED 1\n' \
        > "$work/$v/libavutil/avconfig.h"
    cc -I"$work/$v" "$here/offsets.c" -o "$work/offsets-$v"
    echo "== FFmpeg $v"
    "$work/offsets-$v"
done
