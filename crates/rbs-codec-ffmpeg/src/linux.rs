//! Linux engine over libavcodec's native AAC encoder, loaded at run time.
//!
//! This is the adapter's low-level module (principle P11): every `unsafe` block states
//! its invariant.
//!
//! # Binary interface
//!
//! FFmpeg keeps its ABI stable within a major version of each library: fields are only
//! appended to public structs and removed at a major bump. The adapter therefore
//! supports the majors it has a layout for ([`LAYOUTS`], generated from the public
//! headers of FFmpeg 6.1, 7.0 and 8.0 by `tools/offsets.sh`), and only with the
//! libavutil major each libavcodec major ships with. It sets every encoder parameter it
//! can through `AVOptions` (by name, layout-free) and touches struct fields only where
//! no option exists: the context's `sample_fmt`, `frame_size` and `initial_padding`, and
//! the frame's `data`, `nb_samples`, `format`, `pts` and `ch_layout`, and the packet's
//! `data`, `size`. Before a session is used, the layout is checked against the library
//! itself: a fresh context's `sample_fmt` reads `AV_SAMPLE_FMT_NONE`, and after opening,
//! `frame_size` read through the layout equals the `frame_size` option and 1024, and
//! `initial_padding` is 1024. A mismatch refuses the session (`CreateError::Device`)
//! instead of writing through a wrong offset.

use std::ffi::{CStr, c_char, c_int, c_uint, c_void};
use std::ptr;
use std::sync::OnceLock;

use libloading::Library;
use rbs_codec::{AudioEncoder, AudioEncoderConfig, AudioEncoderFactory, CreateError, EncodeError};
use rbs_core::capability::CapabilitySet;
use rbs_core::registry::{AdapterFactory, AdapterId, ProbeError};

use crate::session::{self, Checked, Engine, FRAME, Output, Session, delegate_audio_encoder};

/// `AV_SAMPLE_FMT_FLTP`: planar `f32`, the AAC encoder's only input format.
const AV_SAMPLE_FMT_FLTP: c_int = 8;
/// `AV_SAMPLE_FMT_NONE`: a fresh context's sample format.
const AV_SAMPLE_FMT_NONE: c_int = -1;
/// `AVERROR(EAGAIN)` on Linux.
const AVERROR_EAGAIN: c_int = -11;
/// `AVERROR_EOF`: `-MKTAG('E', 'O', 'F', ' ')`.
const AVERROR_EOF: c_int = -0x2046_4F45;
/// The encoder's `initial_padding` (its delay) and `frame_size`.
const AAC_DELAY: c_int = 1024;

/// Byte offsets of the fields the adapter reads or writes, for one pair of majors.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Layout {
    /// libavcodec major (`avcodec_version() >> 16`).
    pub avcodec: c_uint,
    /// libavutil major it ships with.
    pub avutil: c_uint,
    pub ctx_sample_fmt: usize,
    pub ctx_frame_size: usize,
    pub ctx_initial_padding: usize,
    pub frame_ch_layout: usize,
}

/// `AVFrame` fields at the same offset in every supported major.
const FRAME_DATA: usize = 0;
const FRAME_NB_SAMPLES: usize = 112;
const FRAME_FORMAT: usize = 116;
const FRAME_PTS: usize = 136;
/// `AVPacket` fields at the same offset in every supported major.
const PACKET_DATA: usize = 24;
const PACKET_SIZE: usize = 32;

/// Generated by `tools/offsets.sh` (LP64: x86_64 and aarch64 Linux). Newest first.
pub(crate) const LAYOUTS: [Layout; 3] = [
    // FFmpeg 8.0
    Layout {
        avcodec: 62,
        avutil: 60,
        ctx_sample_fmt: 348,
        ctx_frame_size: 376,
        ctx_initial_padding: 396,
        frame_ch_layout: 384,
    },
    // FFmpeg 7.0
    Layout {
        avcodec: 61,
        avutil: 59,
        ctx_sample_fmt: 348,
        ctx_frame_size: 376,
        ctx_initial_padding: 396,
        frame_ch_layout: 408,
    },
    // FFmpeg 6.x
    Layout {
        avcodec: 60,
        avutil: 58,
        ctx_sample_fmt: 360,
        ctx_frame_size: 364,
        ctx_initial_padding: 700,
        frame_ch_layout: 448,
    },
];

type VersionFn = unsafe extern "C" fn() -> c_uint;
type FindEncoderByNameFn = unsafe extern "C" fn(*const c_char) -> *const c_void;
type AllocContextFn = unsafe extern "C" fn(*const c_void) -> *mut c_void;
type OpenFn = unsafe extern "C" fn(*mut c_void, *const c_void, *mut *mut c_void) -> c_int;
type FreePtrFn = unsafe extern "C" fn(*mut *mut c_void);
type SendFrameFn = unsafe extern "C" fn(*mut c_void, *const c_void) -> c_int;
type ReceivePacketFn = unsafe extern "C" fn(*mut c_void, *mut c_void) -> c_int;
type AllocFn = unsafe extern "C" fn() -> *mut c_void;
type UnrefFn = unsafe extern "C" fn(*mut c_void);
type FrameIntFn = unsafe extern "C" fn(*mut c_void, c_int) -> c_int;
type FrameFn = unsafe extern "C" fn(*mut c_void) -> c_int;
type OptSetFn = unsafe extern "C" fn(*mut c_void, *const c_char, *const c_char, c_int) -> c_int;
type OptSetIntFn = unsafe extern "C" fn(*mut c_void, *const c_char, i64, c_int) -> c_int;
type OptGetIntFn = unsafe extern "C" fn(*mut c_void, *const c_char, c_int, *mut i64) -> c_int;
type LayoutDefaultFn = unsafe extern "C" fn(*mut c_void, c_int);
type StrErrorFn = unsafe extern "C" fn(c_int, *mut c_char, usize) -> c_int;
type LogSetLevelFn = unsafe extern "C" fn(c_int);

/// `AV_LOG_ERROR`: libavutil's log level for errors only.
const AV_LOG_ERROR: c_int = 16;
/// `AVFrame.extended_data`, which libavutil points at `data` for planar audio with at
/// most 8 channels (frame layout check).
const FRAME_EXTENDED_DATA: usize = 96;

/// The libavcodec and libavutil entry points.
pub(crate) struct Api {
    pub layout: Layout,
    find_encoder_by_name: FindEncoderByNameFn,
    alloc_context: AllocContextFn,
    open: OpenFn,
    free_context: FreePtrFn,
    send_frame: SendFrameFn,
    receive_packet: ReceivePacketFn,
    packet_alloc: AllocFn,
    packet_free: FreePtrFn,
    packet_unref: UnrefFn,
    frame_alloc: AllocFn,
    frame_free: FreePtrFn,
    frame_get_buffer: FrameIntFn,
    frame_make_writable: FrameFn,
    opt_set: OptSetFn,
    opt_set_int: OptSetIntFn,
    opt_get_int: OptGetIntFn,
    channel_layout_default: LayoutDefaultFn,
    strerror: StrErrorFn,
    log_set_level: LogSetLevelFn,
    // Kept loaded for the life of the process: the function pointers above point
    // into these libraries.
    _avcodec: Library,
    _avutil: Library,
}

fn open_library(name: &str) -> Result<Library, String> {
    // SAFETY: loading a shared library runs its initialisers. FFmpeg's libraries are
    // designed to be loaded by any process with `dlopen`.
    unsafe { Library::new(name) }.map_err(|e| format!("{name}: {e}"))
}

/// Looks up `name` (NUL-terminated) as a `T`.
///
/// # Safety
///
/// `T` must be the function pointer type of the symbol's C prototype.
unsafe fn symbol<T: Copy>(lib: &Library, name: &[u8]) -> Result<T, String> {
    // SAFETY: the caller guarantees the type.
    unsafe { lib.get::<T>(name) }
        .map(|s| *s)
        .map_err(|e| format!("{}: {e}", String::from_utf8_lossy(name)))
}

fn load_layout(layout: Layout) -> Result<Api, String> {
    let avcodec = open_library(&format!("libavcodec.so.{}", layout.avcodec))?;
    let avutil = open_library(&format!("libavutil.so.{}", layout.avutil))?;
    // SAFETY: every type is the prototype of the symbol in libavcodec/avcodec.h,
    // libavcodec/packet.h, libavutil/frame.h, opt.h, channel_layout.h and error.h of
    // the supported majors (pointers to FFmpeg structs as `c_void`).
    unsafe {
        let codec_version: VersionFn = symbol(&avcodec, b"avcodec_version\0")?;
        let util_version: VersionFn = symbol(&avutil, b"avutil_version\0")?;
        let (c, u) = (codec_version() >> 16, util_version() >> 16);
        if (c, u) != (layout.avcodec, layout.avutil) {
            return Err(format!(
                "libavcodec {c} with libavutil {u}; expected {} with {}",
                layout.avcodec, layout.avutil
            ));
        }
        Ok(Api {
            layout,
            find_encoder_by_name: symbol(&avcodec, b"avcodec_find_encoder_by_name\0")?,
            alloc_context: symbol(&avcodec, b"avcodec_alloc_context3\0")?,
            open: symbol(&avcodec, b"avcodec_open2\0")?,
            free_context: symbol(&avcodec, b"avcodec_free_context\0")?,
            send_frame: symbol(&avcodec, b"avcodec_send_frame\0")?,
            receive_packet: symbol(&avcodec, b"avcodec_receive_packet\0")?,
            packet_alloc: symbol(&avcodec, b"av_packet_alloc\0")?,
            packet_free: symbol(&avcodec, b"av_packet_free\0")?,
            packet_unref: symbol(&avcodec, b"av_packet_unref\0")?,
            frame_alloc: symbol(&avutil, b"av_frame_alloc\0")?,
            frame_free: symbol(&avutil, b"av_frame_free\0")?,
            frame_get_buffer: symbol(&avutil, b"av_frame_get_buffer\0")?,
            frame_make_writable: symbol(&avutil, b"av_frame_make_writable\0")?,
            opt_set: symbol(&avutil, b"av_opt_set\0")?,
            opt_set_int: symbol(&avutil, b"av_opt_set_int\0")?,
            opt_get_int: symbol(&avutil, b"av_opt_get_int\0")?,
            channel_layout_default: symbol(&avutil, b"av_channel_layout_default\0")?,
            strerror: symbol(&avutil, b"av_strerror\0")?,
            log_set_level: symbol(&avutil, b"av_log_set_level\0")?,
            _avcodec: avcodec,
            _avutil: avutil,
        })
    }
}

/// The newest supported FFmpeg on this system, loaded once per process.
pub(crate) fn api() -> Result<&'static Api, String> {
    static API: OnceLock<Result<Api, String>> = OnceLock::new();
    API.get_or_init(|| {
        let mut why = Vec::new();
        for layout in LAYOUTS {
            match load_layout(layout) {
                Ok(api) => {
                    // libavcodec logs informational lines (the AAC encoder prints its
                    // statistics when a context closes) to stderr. The level is
                    // process-wide; RBS uses FFmpeg only through this adapter.
                    // SAFETY: plain call with a valid level.
                    unsafe { (api.log_set_level)(AV_LOG_ERROR) };
                    return Ok(api);
                }
                Err(e) => why.push(e),
            }
        }
        Err(format!(
            "no supported FFmpeg (6, 7 or 8) found: {}",
            why.join("; ")
        ))
    })
    .as_ref()
    .map_err(Clone::clone)
}

impl Api {
    /// The `aac` encoder, or null.
    fn aac(&self) -> *const c_void {
        // SAFETY: a NUL-terminated name; the call only searches the codec list.
        unsafe { (self.find_encoder_by_name)(c"aac".as_ptr()) }
    }

    fn error(&self, what: &str, code: c_int) -> String {
        let mut buf = [0 as c_char; 128];
        // SAFETY: `buf` is writable for its whole length, which is passed; av_strerror
        // always NUL-terminates.
        let text = unsafe {
            (self.strerror)(code, buf.as_mut_ptr(), buf.len());
            CStr::from_ptr(buf.as_ptr())
        };
        format!("{what}: {} ({code})", text.to_string_lossy())
    }
}

/// Reads a `T` at `offset` bytes into an FFmpeg struct.
///
/// # Safety
///
/// `base` points to a live struct whose field at `offset` has type `T` (the layout
/// table for the loaded major).
unsafe fn read<T: Copy>(base: *const c_void, offset: usize) -> T {
    // SAFETY: guaranteed by the caller; FFmpeg structs are naturally aligned.
    unsafe { base.cast::<u8>().add(offset).cast::<T>().read() }
}

/// Writes a `T` at `offset` bytes into an FFmpeg struct.
///
/// # Safety
///
/// As [`read`], and the struct is not used by another thread meanwhile.
unsafe fn write<T>(base: *mut c_void, offset: usize, value: T) {
    // SAFETY: guaranteed by the caller.
    unsafe { base.cast::<u8>().add(offset).cast::<T>().write(value) }
}

/// Factory of the FFmpeg AAC adapter.
#[derive(Debug, Default)]
pub struct FfmpegAacFactory;

impl FfmpegAacFactory {
    /// Creates the factory. Does nothing until used.
    pub fn new() -> Self {
        Self
    }

    /// Creates a session with its concrete type.
    pub fn create_session(
        &self,
        config: &AudioEncoderConfig,
    ) -> Result<FfmpegAacSession, CreateError> {
        let checked = session::check(config)?;
        let api = api().map_err(|e| CreateError::Unsupported { what: e })?;
        let engine = AvEngine::new(api, &checked)?;
        Ok(FfmpegAacSession(Session::new(engine, &checked)))
    }
}

impl AdapterFactory for FfmpegAacFactory {
    fn id(&self) -> AdapterId {
        AdapterId::new(crate::ADAPTER_ID)
    }

    fn display_name(&self) -> &str {
        "FFmpeg AAC"
    }

    fn probe(&self) -> Result<CapabilitySet, ProbeError> {
        // The libraries and their encoder list cannot change while the process runs.
        static AVAILABLE: OnceLock<bool> = OnceLock::new();
        let available = *AVAILABLE.get_or_init(|| api().is_ok_and(|a| !a.aac().is_null()));
        Ok(if available {
            session::capabilities()
        } else {
            CapabilitySet::new()
        })
    }
}

impl AudioEncoderFactory for FfmpegAacFactory {
    fn create(&self, config: &AudioEncoderConfig) -> Result<Box<dyn AudioEncoder>, CreateError> {
        Ok(Box::new(self.create_session(config)?))
    }
}

