/// An open `AVCodecContext`, freed on drop.
struct Context {
    api: &'static Api,
    ptr: *mut c_void,
}

impl Drop for Context {
    fn drop(&mut self) {
        // SAFETY: `ptr` came from avcodec_alloc_context3 and is freed once here.
        unsafe { (self.api.free_context)(&mut self.ptr) };
    }
}

impl Context {
    /// Allocates, configures and opens the `aac` encoder, then checks the layout.
    fn open(api: &'static Api, checked: &Checked) -> Result<Self, CreateError> {
        let codec = api.aac();
        if codec.is_null() {
            return Err(CreateError::Unsupported {
                what: "this FFmpeg has no aac encoder".into(),
            });
        }
        // SAFETY: `codec` is the encoder found above.
        let ptr = unsafe { (api.alloc_context)(codec) };
        if ptr.is_null() {
            return Err(CreateError::Device("avcodec_alloc_context3 failed".into()));
        }
        let ctx = Context { api, ptr };
        let layout = api.layout;
        let device = |what: &str, code: c_int| CreateError::Device(api.error(what, code));
        // SAFETY: `ptr` is a live context of the loaded major; the layout check reads
        // an `int` (enum) field.
        let fresh: c_int = unsafe { read(ptr, layout.ctx_sample_fmt) };
        if fresh != AV_SAMPLE_FMT_NONE {
            return Err(CreateError::Device(format!(
                "libavcodec {} layout check failed: sample_fmt reads {fresh}",
                layout.avcodec
            )));
        }
        let rate = checked.format.sample_rate.hz();
        let channels = if checked.channels == 1 {
            c"mono"
        } else {
            c"stereo"
        };
        let time_base = std::ffi::CString::new(format!("1/{rate}"))
            .map_err(|e| CreateError::InvalidConfig(e.to_string()))?;
        let bitrate = i64::try_from(checked.bitrate_bps)
            .map_err(|e| CreateError::InvalidConfig(e.to_string()))?;
        // SAFETY: AVCodecContext is an AVOptions object (its first field is its
        // AVClass); names and values are NUL-terminated and outlive the calls. The
        // sample format is written through the checked layout.
        unsafe {
            for (name, value) in [(c"b", bitrate), (c"ar", i64::from(rate)), (c"threads", 1)] {
                let r = (api.opt_set_int)(ptr, name.as_ptr(), value, 0);
                if r < 0 {
                    return Err(device(&format!("option {name:?}"), r));
                }
            }
            for (name, value) in [
                (c"ch_layout", channels),
                (c"time_base", time_base.as_c_str()),
            ] {
                let r = (api.opt_set)(ptr, name.as_ptr(), value.as_ptr(), 0);
                if r < 0 {
                    return Err(device(&format!("option {name:?}"), r));
                }
            }
            write(ptr, layout.ctx_sample_fmt, AV_SAMPLE_FMT_FLTP);
            let r = (api.open)(ptr, codec, ptr::null_mut());
            if r < 0 {
                return Err(device("avcodec_open2", r));
            }
        }
        let mut by_option = 0i64;
        // SAFETY: as above; `by_option` is a valid out pointer. The two reads are
        // `int` fields of the open context.
        let (r, frame_size, padding) = unsafe {
            let r = (api.opt_get_int)(ptr, c"frame_size".as_ptr(), 0, &mut by_option);
            let f: c_int = read(ptr, layout.ctx_frame_size);
            let p: c_int = read(ptr, layout.ctx_initial_padding);
            (r, f, p)
        };
        if r < 0
            || i64::from(frame_size) != by_option
            || frame_size != AAC_DELAY
            || padding != AAC_DELAY
        {
            return Err(CreateError::Device(format!(
                "libavcodec {} layout check failed: frame_size {frame_size} (option {by_option}), initial_padding {padding}",
                layout.avcodec
            )));
        }
        Ok(ctx)
    }
}

/// The encoder context, its one input frame and its one output packet.
pub struct AvEngine {
    api: &'static Api,
    checked: Checked,
    ctx: Option<Context>,
    frame: *mut c_void,
    packet: *mut c_void,
    /// Samples sent on the current context (the frame's `pts`, in 1/rate units).
    pts: i64,
    contexts: u64,
}

// SAFETY: the context, frame and packet are owned by this engine alone and used only
// through `&mut self`, so never from two threads at once; libavcodec contexts may move
// between threads (FFmpeg only forbids concurrent use).
unsafe impl Send for AvEngine {}

impl Drop for AvEngine {
    fn drop(&mut self) {
        self.ctx = None;
        // SAFETY: both came from their alloc functions and are freed once here;
        // av_*_free accept a pointer to null.
        unsafe {
            (self.api.frame_free)(&mut self.frame);
            (self.api.packet_free)(&mut self.packet);
        }
    }
}

impl AvEngine {
    fn new(api: &'static Api, checked: &Checked) -> Result<Self, CreateError> {
        let ctx = Context::open(api, checked)?;
        // SAFETY: plain allocations; null is checked below and accepted by Drop.
        let (frame, packet) = unsafe { ((api.frame_alloc)(), (api.packet_alloc)()) };
        let engine = Self {
            api,
            checked: *checked,
            ctx: Some(ctx),
            frame,
            packet,
            pts: 0,
            contexts: 1,
        };
        if frame.is_null() || packet.is_null() {
            return Err(CreateError::Device(
                "av_frame_alloc or av_packet_alloc failed".into(),
            ));
        }
        let layout = api.layout;
        // SAFETY: `frame` is a fresh AVFrame of the loaded major: `nb_samples` and
        // `format` are `int`s, `ch_layout` an AVChannelLayout that
        // av_channel_layout_default initialises; av_frame_get_buffer then allocates
        // one buffer per channel for those parameters.
        let r = unsafe {
            write(frame, FRAME_NB_SAMPLES, FRAME as c_int);
            write(frame, FRAME_FORMAT, AV_SAMPLE_FMT_FLTP);
            (api.channel_layout_default)(
                frame.cast::<u8>().add(layout.frame_ch_layout).cast(),
                checked.channels as c_int,
            );
            (api.frame_get_buffer)(frame, 0)
        };
        if r < 0 {
            return Err(CreateError::Device(api.error("av_frame_get_buffer", r)));
        }
        // Frame layout check before any sample is written: libavutil points
        // `extended_data` at `data` and fills one plane per channel.
        // SAFETY: `frame` is live; both reads are pointer fields of the loaded major.
        let laid_out = unsafe {
            let extended: *const c_void = read(frame, FRAME_EXTENDED_DATA);
            extended == frame.cast_const()
                && (0..checked.channels).all(|c| {
                    !read::<*const c_void>(frame, FRAME_DATA + c * size_of::<*mut u8>()).is_null()
                })
        };
        if !laid_out {
            return Err(CreateError::Device(format!(
                "libavutil {} layout check failed: the frame's planes are not where expected",
                layout.avutil
            )));
        }
        Ok(engine)
    }

    fn failed(&self, what: &str, code: c_int) -> EncodeError {
        EncodeError::Failed {
            reason: self.api.error(what, code),
            recoverable: false,
        }
    }

    /// Sends `frame` (null: end of stream) and pushes every packet it releases.
    fn send(&mut self, frame: *const c_void, out: &mut Output) -> Result<(), EncodeError> {
        let Some(ctx) = &self.ctx else {
            return Err(EncodeError::Failed {
                reason: "the AAC encoder has no open context".into(),
                recoverable: false,
            });
        };
        let ctx = ctx.ptr;
        // SAFETY: `ctx` is open; `frame` is this engine's frame or null.
        let r = unsafe { (self.api.send_frame)(ctx, frame) };
        if r < 0 {
            return Err(self.failed("avcodec_send_frame", r));
        }
        loop {
            // SAFETY: `ctx` is open and `packet` is this engine's unreferenced packet.
            let r = unsafe { (self.api.receive_packet)(ctx, self.packet) };
            if r == AVERROR_EAGAIN || r == AVERROR_EOF {
                return Ok(());
            }
            if r < 0 {
                return Err(self.failed("avcodec_receive_packet", r));
            }
            // SAFETY: a received packet holds `size` bytes at `data` until unref;
            // both fields are at the same offset in every supported major.
            let pushed = unsafe {
                let data: *const u8 = read(self.packet, PACKET_DATA);
                let size: c_int = read(self.packet, PACKET_SIZE);
                let bytes = if data.is_null() || size <= 0 {
                    &[][..]
                } else {
                    std::slice::from_raw_parts(data, size as usize)
                };
                let pushed = out.push(bytes);
                (self.api.packet_unref)(self.packet);
                pushed
            };
            pushed?;
        }
    }
}

impl Engine for AvEngine {
    fn encode(&mut self, planar: &[f32], out: &mut Output) -> Result<(), EncodeError> {
        let api = self.api;
        if self.ctx.is_none() {
            // The first frame of a timeline after `finish`: a fresh context (a
            // control-rate event, after discontinuities and flushes only).
            let ctx = Context::open(api, &self.checked).map_err(|e| EncodeError::Failed {
                reason: e.to_string(),
                recoverable: false,
            })?;
            self.ctx = Some(ctx);
            self.contexts += 1;
            self.pts = 0;
        }
        // SAFETY: `frame` holds buffers for `FRAME` samples on each channel (set up in
        // `new`); make_writable gives it back its own buffers if the encoder still
        // referenced them (libavcodec's AAC encoder copies its input, so normally it
        // does nothing). `data[c]` are `FRAME` floats each; `pts` is an int64_t.
        unsafe {
            let r = (api.frame_make_writable)(self.frame);
            if r < 0 {
                return Err(self.failed("av_frame_make_writable", r));
            }
            for (c, plane) in planar.chunks_exact(FRAME).enumerate() {
                let dst: *mut f32 = read(self.frame, FRAME_DATA + c * size_of::<*mut u8>());
                ptr::copy_nonoverlapping(plane.as_ptr(), dst, FRAME);
            }
            write(self.frame, FRAME_PTS, self.pts);
        }
        self.pts += FRAME as i64;
        self.send(self.frame, out)
    }

    fn finish(&mut self, out: &mut Output) -> Result<(), EncodeError> {
        if self.ctx.is_none() {
            // Nothing was encoded since the last end of stream.
            return Ok(());
        }
        self.send(ptr::null(), out)?;
        // The AAC encoder cannot continue after end of stream: the next frame opens a
        // fresh context, so a flush before drop opens none.
        self.ctx = None;
        Ok(())
    }
}
