#!/bin/sh
# Regenerates src/sys/vpl_api.rs from Intel's libvpl API headers (MIT licence).
# Needs bindgen-cli 0.73 and libclang. Run from the repository root. Only types
# and constants are generated; the dispatcher entry points are declared by hand
# in src/sys/mod.rs and loaded at run time.
set -eu
TAG=v2.13.0
OUT=${OUT:-crates/rbs-codec-qsv/src/sys/vpl_api.rs}
TMP=$(mktemp -d)
BASE="https://raw.githubusercontent.com/intel/libvpl/$TAG/api/vpl"
mkdir -p "$TMP/vpl"
# Headers that do not exist at this tag (404) are skipped.
for h in mfx.h mfxadapter.h mfxbrc.h mfxcamera.h mfxcommon.h mfxdefs.h mfxdeprecated.h \
  mfxdispatcher.h mfxdispatcherprefixedfunctions.h mfxencodestats.h mfxenctools.h \
  mfximplcaps.h mfxjpeg.h mfxmemory.h mfxmvc.h mfxpcp.h mfxsession.h mfxstructures.h \
  mfxsurfacepool.h mfxvideo.h mfxvp8.h; do
  curl -sSfL -o "$TMP/vpl/$h" "$BASE/$h" 2>/dev/null || true
done
bindgen "$TMP/vpl/mfx.h" \
  --allowlist-type 'mfx.*' --allowlist-var 'MFX_.*' --blocklist-function '.*' \
  --no-doc-comments --use-core --default-enum-style consts --no-prepend-enum-name \
  --rust-target 1.87 --with-derive-default --no-debug '.*' \
  --raw-line "// Generated by bindgen 0.73.2 from Intel libvpl $TAG (api/vpl/mfx.h, oneVPL API 2.13," \
  --raw-line '// MIT licence, "Copyright Intel Corporation"). Do not edit; regenerate with' \
  --raw-line '// crates/rbs-codec-qsv/tools/bindgen.sh.' \
  -o "$OUT" -- -I"$TMP/vpl" -I"$TMP"
rm -rf "$TMP"
