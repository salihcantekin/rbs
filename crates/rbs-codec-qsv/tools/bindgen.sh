#!/bin/sh
# Regenerates src/sys/vpl_api.rs from Intel's oneVPL API headers (libvpl, MIT
# licence). Needs bindgen-cli 0.73 and libclang. Run from the repository root.
# Bumping the API version also means updating MIN_API in src/sys/mod.rs.
set -eu
TAG=v2.13.0
OUT=crates/rbs-codec-qsv/src/sys/vpl_api.rs
TMP=$(mktemp -d)
mkdir -p "$TMP/vpl"
for h in mfx.h mfxdefs.h mfxcommon.h mfxstructures.h mfxdispatcher.h mfximplcaps.h \
  mfxsession.h mfxvideo.h mfxadapter.h mfxbrc.h mfxmvc.h mfxpcp.h mfxvp8.h mfxjpeg.h \
  mfxsurfacepool.h mfxmemory.h mfxdispatcherprefixedfunctions.h; do
  curl -sSfL -o "$TMP/vpl/$h" "https://raw.githubusercontent.com/intel/libvpl/$TAG/api/vpl/$h"
done
bindgen "$TMP/vpl/mfx.h" \
  --allowlist-type 'mfx.*' --allowlist-var 'MFX_.*' --blocklist-function '.*' \
  --no-doc-comments --use-core --default-enum-style consts --no-prepend-enum-name \
  --rust-target 1.87 --with-derive-default --no-debug '.*' \
  --raw-line "// Generated by bindgen 0.73.2 from Intel libvpl $TAG (api/vpl/mfx.h, oneVPL API 2.13," \
  --raw-line '// MIT licence, "Copyright Intel Corporation"). Do not edit; regenerate with' \
  --raw-line '// crates/rbs-codec-qsv/tools/bindgen.sh.' \
  -o "$OUT" -- -I"$TMP/vpl"
rm -rf "$TMP"
