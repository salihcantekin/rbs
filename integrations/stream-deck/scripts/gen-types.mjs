// Generates src/rbs-client/generated.ts from the Control API schemas in
// crates/rbs-api/schemas (ADR-0198 decision 4). `--check` fails when the checked-in
// file differs (used by the tests).
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "..", "..", "crates", "rbs-api", "schemas");
const out = join(root, "src", "rbs-client", "generated.ts");

/** The methods the plugin calls. Adding a call means adding its name here. */
export const METHODS = [
	"session.hello",
	"session.authenticate",
	"events.subscribe",
	"scene.list",
	"scene.switch",
	"source.list",
	"item.set_visible",
	"source.set_muted",
	"canvas.set_master_muted",
	"record.status",
	"record.start",
	"record.stop",
	"record.pause_toggle",
	"record.pause",
	"record.resume",
	"profile.list",
	"stream.status",
	"stream.start",
	"stream.stop",
	"output.profiles",
	"source.set_volume",
	"canvas.set_master_volume",
	"replay.save",
	"replay.status",
	"vcam.start",
	"vcam.stop",
	"vcam.status",
	"marker.add",
	"canvas.set_preview",
	"canvas.transition",
	"collection.list",
	"collection.switch",
	"profile.switch",
	"replay.arm",
	"replay.disarm",
	"bus.list",
	"bus.set",
	"filter.set_enabled",
];

const pascal = (m) => m.split(/[._]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");

export async function generate() {
	const all = {};
	for (const f of readdirSync(schemaDir).filter((f) => f.endsWith(".json")).sort()) {
		Object.assign(all, JSON.parse(readFileSync(join(schemaDir, f), "utf8")));
	}
	let text =
		"// GENERATED by scripts/gen-types.mjs from crates/rbs-api/schemas. Do not edit.\n" +
		"/* eslint-disable */\n\n";
	const table = [];
	for (const m of METHODS) {
		const s = all[m];
		if (!s) throw new Error(`method ${m} is not in the schemas`);
		const name = pascal(m);
		for (const [kind, suffix] of [["input_schema", "Params"], ["output_schema", "Result"]]) {
			const schema = { ...s[kind], title: "Root" };
			const body = await compile(schema, "Root", {
				bannerComment: "",
				declareExternallyReferenced: true,
				additionalProperties: false,
				style: { singleQuote: false, useTabs: true },
				strictIndexSignatures: true,
			});
			// One namespace per method and direction: definitions of different methods
			// share names (Snapshot, ...) and are not the same type.
			text += `export namespace ${name}${suffix} {\n${body.replace(/^(?=.)/gm, "\t")}}\n`;
		}
		table.push(`\t${JSON.stringify(m)}: { params: ${name}Params.Root; result: ${name}Result.Root };`);
	}
	text += `/** Every method the plugin calls, with its parameter and answer types. */\nexport interface Methods {\n${table.join("\n")}\n}\n`;
	return text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const text = await generate();
	if (process.argv.includes("--check")) {
		const have = readFileSync(out, "utf8");
		if (have !== text) {
			console.error("src/rbs-client/generated.ts is out of date: run `npm run gen-types`");
			process.exit(1);
		}
	} else {
		writeFileSync(out, text);
		console.log(`wrote ${out}`);
	}
}
