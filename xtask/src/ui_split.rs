//! The name rules of the split UI crates (ADR-0138 decisions 2, 4 and 5), checked by
//! `cargo xtask check-ui`. Slint 1.18 matches library types by name, so a missed export
//! or a same-named declaration elsewhere would quietly give a window crate its own copy
//! of a type. Every breach is an error; there is no baseline.
//!
//! - Base files (`base/`) import only base files, `tokens.slint` and Slint's own files.
//! - The base root exports every global, struct and enum of the base files and of
//!   `tokens.slint` by its declared name: no `export *`, no `as`.
//! - No file outside `base/` declares a global, struct or enum with a base name.
//! - Only the window roots (`roots/`, not `single.slint`) import `@rbsui`, and each
//!   imports every base name.
//! - A window root exports windows only: names it imports from their own files, never
//!   through `app.slint` (which reaches every file, so any change would rebuild every
//!   window crate).
//! - The windows of the window roots together equal the windows of `roots/single.slint`
//!   (the live preview's build).
//! - The facade (`crates/rbs-app-ui/src/lib.rs`) re-exports exactly the base names, so
//!   every type Rust sees comes from the base.

use std::collections::BTreeSet;

/// The names `tokens.slint` declares (generated by `rbs_ui::tokens_slint`).
pub const TOKEN_NAMES: &[&str] = &["Theme", "Tokens", "ThemeSlot"];

/// The facade crate's source, relative to the repository root.
pub const FACADE: &str = "crates/rbs-app-ui/src/lib.rs";

const BASE_ROOT: &str = "base/root.slint";
const SINGLE_ROOT: &str = "roots/single.slint";
const LIBRARY: &str = "\"@rbsui\"";

/// Checks the rules over `(path under crates/rbs-app/ui, text)` pairs and the facade's
/// source. Returns one message per breach.
pub fn check(files: &[(String, String)], facade: &str) -> Vec<String> {
    let mut errors = Vec::new();
    let code: Vec<(&str, String)> = files
        .iter()
        .map(|(name, text)| (name.as_str(), strip_comments(text)))
        .collect();
    let Some(base_root) = code.iter().find(|(n, _)| *n == BASE_ROOT) else {
        return vec![format!("{BASE_ROOT} is missing (ADR-0138 decision 2)")];
    };

    // Names the base declares, and what its root exports.
    let mut base_names: BTreeSet<String> = TOKEN_NAMES.iter().map(|n| (*n).to_owned()).collect();
    for (name, text) in &code {
        if name.starts_with("base/") {
            base_names.extend(declared_types(text));
            for target in imports(text).into_iter().map(|(_, from)| from) {
                let ok = target.ends_with(".slint") && !target.contains('/')
                    || target == "tokens.slint"
                    || target == "std-widgets.slint";
                if !ok {
                    errors.push(format!(
                        "{name} imports \"{target}\"; a base file imports only base files and tokens.slint"
                    ));
                }
            }
        }
    }
    let root_text = &base_root.1;
    if root_text.contains("export *") || export_lists(root_text).iter().any(|l| l.contains(" as "))
    {
        errors.push(format!(
            "{BASE_ROOT} uses `export *` or `as`; export each name as declared"
        ));
    }
    let exported: BTreeSet<String> = export_lists(root_text)
        .iter()
        .flat_map(|l| names(l))
        .collect();
    for missing in base_names.difference(&exported) {
        errors.push(format!("{BASE_ROOT} does not export {missing}"));
    }

    let mut window_exports: BTreeSet<String> = BTreeSet::new();
    let mut single_windows: BTreeSet<String> = BTreeSet::new();
    for (name, text) in &code {
        if !name.starts_with("base/") {
            for clash in declared_types(text).intersection(&base_names) {
                errors.push(format!(
                    "{name} declares {clash}, a name of the base library; declare it only in base/"
                ));
            }
        }
        let is_window_root = name.starts_with("roots/") && *name != SINGLE_ROOT;
        let uses_library = imports(text)
            .iter()
            .any(|(_, from)| format!("\"{from}\"") == LIBRARY);
        if uses_library && !is_window_root {
            errors.push(format!("{name} imports @rbsui; only window roots do"));
        }
        if is_window_root {
            let from_library: BTreeSet<String> = imports(text)
                .into_iter()
                .filter(|(_, from)| from == "@rbsui")
                .flat_map(|(list, _)| names(&list))
                .collect();
            for missing in base_names.difference(&from_library) {
                errors.push(format!("{name} does not import {missing} from @rbsui"));
            }
            let windows: BTreeSet<String> = imports(text)
                .into_iter()
                .filter(|(_, from)| from.starts_with("../") && !from.starts_with("../base/"))
                .flat_map(|(list, _)| names(&list))
                .collect();
            if imports(text).iter().any(|(_, from)| from == "../app.slint") {
                errors.push(format!(
                    "{name} imports app.slint, which imports every window: each UI change would \
                     rebuild every window crate. Import the windows from their own files."
                ));
            }
            for list in export_lists(text) {
                for exported in names(&list) {
                    if !windows.contains(&exported) {
                        errors.push(format!(
                            "{name} exports {exported}; a window root exports only windows it imports from their files"
                        ));
                    }
                    window_exports.insert(exported);
                }
            }
        }
        if *name == SINGLE_ROOT {
            single_windows = export_lists(text)
                .iter()
                .flat_map(|l| names(l))
                .filter(|n| !base_names.contains(n))
                .collect();
        }
    }
    if window_exports != single_windows {
        errors.push(format!(
            "the window roots export {window_exports:?} but {SINGLE_ROOT} exports {single_windows:?}; \
             the live preview build must have the same windows (ADR-0138 decision 5)"
        ));
    }

    let facade_types: BTreeSet<String> = facade_types(&strip_comments(facade));
    if facade_types != base_names {
        let extra: Vec<_> = facade_types.difference(&base_names).collect();
        let missing: Vec<_> = base_names.difference(&facade_types).collect();
        errors.push(format!(
            "rbs-app-ui re-exports types that differ from the base: extra {extra:?}, missing {missing:?}"
        ));
    }
    errors
}

/// The text without `//` and `/* */` comments (string contents kept).
fn strip_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while !rest.is_empty() {
        if let Some(after) = rest.strip_prefix("//") {
            rest = after.find('\n').map_or("", |i| &after[i..]);
        } else if let Some(after) = rest.strip_prefix("/*") {
            rest = after.find("*/").map_or("", |i| &after[i + 2..]);
        } else if rest.starts_with('"') {
            let end = rest[1..].find('"').map_or(rest.len(), |i| i + 2);
            out.push_str(&rest[..end]);
            rest = &rest[end..];
        } else {
            let c = rest.chars().next().unwrap_or(' ');
            out.push(c);
            rest = &rest[c.len_utf8()..];
        }
    }
    out
}

/// Names of top-level `global`, `struct` and `enum` declarations.
fn declared_types(code: &str) -> BTreeSet<String> {
    code.lines()
        .filter_map(|line| {
            let line = line.strip_prefix("export ").unwrap_or(line);
            let mut words = line.split_whitespace();
            match words.next() {
                Some("global" | "struct" | "enum") => words.next().map(|w| ident(w).to_owned()),
                _ => None,
            }
        })
        .filter(|n| !n.is_empty())
        .collect()
}

/// `(names inside the braces, the file)` of every `import { … } from "file";`.
fn imports(code: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut rest = code;
    while let Some(i) = rest.find("import ") {
        rest = &rest[i + "import ".len()..];
        let Some(end) = rest.find(';') else { break };
        let stmt = &rest[..end];
        let list = stmt
            .find('{')
            .zip(stmt.find('}'))
            .map(|(a, b)| stmt[a + 1..b].to_owned())
            .unwrap_or_default();
        let from = stmt.split('"').nth(1).unwrap_or_default().to_owned();
        out.push((list, from));
        rest = &rest[end..];
    }
    out
}

/// The contents of every `export { … }` list.
fn export_lists(code: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = code;
    while let Some(i) = rest.find("export {") {
        rest = &rest[i + "export {".len()..];
        let Some(end) = rest.find('}') else { break };
        out.push(rest[..end].to_owned());
        rest = &rest[end..];
    }
    out
}

/// The names of a `{ … }` list.
fn names(list: &str) -> Vec<String> {
    list.split(',')
        .map(|n| n.trim().to_owned())
        .filter(|n| !n.is_empty())
        .collect()
}

fn ident(word: &str) -> &str {
    let end = word
        .find(|c: char| !(c.is_alphanumeric() || c == '_' || c == '-'))
        .unwrap_or(word.len());
    &word[..end]
}

/// The type names of the facade's `pub use $types::{ … };`.
fn facade_types(code: &str) -> BTreeSet<String> {
    code.find("pub use $types::{")
        .and_then(|i| {
            let rest = &code[i + "pub use $types::{".len()..];
            rest.find('}')
                .map(|end| names(&rest[..end]).into_iter().collect())
        })
        .unwrap_or_default()
}

#[cfg(test)]
#[allow(clippy::expect_used)] // Tests fail by panicking.
mod tests {
    use super::check;

    fn files(list: &[(&str, &str)]) -> Vec<(String, String)> {
        list.iter()
            .map(|(n, t)| ((*n).to_owned(), (*t).to_owned()))
            .collect()
    }

    const FACADE: &str = "pub use $types::{Studio, Row, Theme, Tokens, ThemeSlot};";

    fn good() -> Vec<(&'static str, &'static str)> {
        vec![
            (
                "base/types.slint",
                "import { Theme } from \"tokens.slint\";\nexport global Studio { }\nexport struct Row { a: int }\n",
            ),
            (
                "base/root.slint",
                "import { Studio, Row } from \"types.slint\";\nimport { Theme, Tokens, ThemeSlot } from \"tokens.slint\";\nexport { Studio, Row }\nexport { Theme, Tokens, ThemeSlot }\nexport component RbsUiAnchor inherits Window { }\n",
            ),
            (
                "roots/main.slint",
                "import { Studio, Row, Theme, Tokens, ThemeSlot } from \"@rbsui\";\nimport { MainWindow } from \"../main_window.slint\";\nexport { MainWindow }\n",
            ),
            (
                "roots/single.slint",
                "import { Studio, Row } from \"../base/types.slint\";\nexport { Studio, Row }\nexport { MainWindow }\n",
            ),
            (
                "main_window.slint",
                "import { Studio } from \"base/types.slint\";\nexport component MainWindow inherits Window { }\n",
            ),
        ]
    }

    #[test]
    fn the_tree_follows_the_split_rules() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let files = crate::check_ui::read_tree(&root).expect("the UI files");
        let facade = std::fs::read_to_string(root.join(super::FACADE)).expect("the facade");
        assert_eq!(check(&files, &facade), Vec::<String>::new());
    }

    #[test]
    fn a_good_tree_passes() {
        assert_eq!(check(&files(&good()), FACADE), Vec::<String>::new());
    }

    #[test]
    fn a_window_root_that_imports_app_slint_fails() {
        let mut f = good();
        f[2].1 = "import { Studio, Row, Theme, Tokens, ThemeSlot } from \"@rbsui\";\nimport { MainWindow } from \"../app.slint\";\nexport { MainWindow }\n";
        let errors = check(&files(&f), FACADE);
        assert!(
            errors.iter().any(|e| e.contains("imports app.slint")),
            "{errors:?}"
        );
    }

    #[test]
    fn a_base_name_declared_elsewhere_fails() {
        let mut f = good();
        f.push(("studio.slint", "struct Row { b: int }\n"));
        let errors = check(&files(&f), FACADE);
        assert!(
            errors
                .iter()
                .any(|e| e.contains("studio.slint declares Row")),
            "{errors:?}"
        );
    }

    #[test]
    fn an_unexported_or_aliased_base_name_fails() {
        let mut f = good();
        f[1].1 = "import { Studio, Row } from \"types.slint\";\nexport { Studio as S }\nexport { Theme, Tokens, ThemeSlot }\n";
        let errors = check(&files(&f), FACADE);
        assert!(
            errors.iter().any(|e| e.contains("does not export Row")),
            "{errors:?}"
        );
        assert!(errors.iter().any(|e| e.contains("`as`")), "{errors:?}");
    }

    #[test]
    fn a_window_root_exporting_a_type_or_missing_a_window_fails() {
        let mut f = good();
        f[2].1 = "import { Studio, Row, Theme, Tokens, ThemeSlot } from \"@rbsui\";\nimport { MainWindow } from \"../main_window.slint\";\nexport { Row }\n";
        let errors = check(&files(&f), FACADE);
        assert!(
            errors.iter().any(|e| e.contains("exports Row")),
            "{errors:?}"
        );
        assert!(
            errors.iter().any(|e| e.contains("same windows")),
            "{errors:?}"
        );
    }

    #[test]
    fn the_library_outside_a_window_root_and_a_short_facade_fail() {
        let mut f = good();
        f.push(("studio.slint", "import { Studio } from \"@rbsui\";\n"));
        let errors = check(&files(&f), "pub use $types::{Studio};");
        assert!(
            errors
                .iter()
                .any(|e| e.contains("studio.slint imports @rbsui")),
            "{errors:?}"
        );
        assert!(errors.iter().any(|e| e.contains("missing")), "{errors:?}");
    }
}
