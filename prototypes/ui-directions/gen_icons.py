#!/usr/bin/env python3
"""Writes ui/icons.slint from the icon table of rbs-ui, so the design study draws the
same Tabler paths as the app. Run from this directory: python3 gen_icons.py"""
import re, pathlib
src = pathlib.Path("../../crates/rbs-ui/src/icon.rs").read_text()
body = src[src.index("pub const ICONS"):]
icons = re.findall(r'(line|fill)\(\s*"([a-z0-9-]+)",\s*"([^"]+)",?\s*\)', body)
out = ["// Generated by gen_icons.py from crates/rbs-ui/src/icon.rs. Do not edit.",
       "export global IconPaths {",
       "    public pure function path(name: string) -> string {",
       "        return"]
for i, (_, name, path) in enumerate(icons):
    out.append(f'            {"" if i == 0 else ": "}name == "{name}" ? "{path}"')
out.append('            : "";\n    }')
out.append("    public pure function filled(name: string) -> bool {\n        return "
           + " || ".join(f'name == "{n}"' for k, n, _ in icons if k == "fill") + ";\n    }\n}")
pathlib.Path("ui/icons.slint").write_text("\n".join(out) + "\n")
print(len(icons), "icons")
